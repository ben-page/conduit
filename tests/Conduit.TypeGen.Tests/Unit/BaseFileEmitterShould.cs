using AwesomeAssertions;

namespace Conduit.TypeGen.Tests.Unit;

[TestClass]
public class BaseFileEmitterShould
{
    [TestMethod]
    public void EmitDispatchResultInterface()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export interface DispatchResult<T>");
        result.Should().Contain("data?: T;");
        result.Should().Contain("error?: ConduitError;");
    }

    [TestMethod]
    public void EmitConduitErrorInterfaces()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export interface ConduitError");
        result.Should().Contain("export interface ConduitErrorDetail");
    }

    [TestMethod]
    public void EmitConduitTransportInterface()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export interface ConduitTransport");
        result.Should().Contain("sendRequest<TResult>(type: string, payload: unknown, headers?: Record<string, string>): Promise<DispatchResult<TResult>>;");
        result.Should().Contain("sendEvent(type: string, data: unknown, headers?: Record<string, string>): Promise<void>;");
        result.Should().Contain("subscribe(eventName: string, handler: (data: unknown) => void): Subscription;");
    }

    [TestMethod]
    public void EmitSubscriptionInterface()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export interface Subscription");
        result.Should().Contain("unsubscribe(): void;");
    }

    [TestMethod]
    public void EmitHttpTransportByDefault()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export class HttpTransport implements ConduitTransport");
        result.Should().Contain("async sendRequest<TResult>");
        result.Should().Contain("async sendEvent(");
    }

    [TestMethod]
    public void EmitSignalRTransportByDefault()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("import { HubConnectionBuilder, HubConnection, HubConnectionState } from '@microsoft/signalr';");
        result.Should().Contain("import type { IRetryPolicy, RetryContext } from '@microsoft/signalr';");
        result.Should().Contain("export class SignalRTransport implements ConduitTransport");
    }

    [TestMethod]
    public void EmitSignalRTransportWhenExplicitlyIncluded()
    {
        // Arrange
        var transports = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "Http", "SignalR" };

        // Act
        var result = BaseFileEmitter.Emit(transports, "/api/conduit", "/conduit");

        // Assert
        result.Should().Contain("export class SignalRTransport");
        result.Should().Contain("import { HubConnectionBuilder, HubConnection, HubConnectionState }");
    }

    [TestMethod]
    public void OmitSignalRTransportWhenHttpOnly()
    {
        // Arrange
        var transports = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "Http" };

        // Act
        var result = BaseFileEmitter.Emit(transports, "/api/conduit", "/conduit");

        // Assert
        result.Should().NotContain("export class SignalRTransport");
        result.Should().NotContain("@microsoft/signalr");
        result.Should().NotContain("HubConnection");
        result.Should().NotContain("DEFAULT_RETRY_POLICY");
    }

    [TestMethod]
    public void AlwaysEmitHttpTransport()
    {
        // Arrange
        var transports = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "Http" };

        // Act
        var result = BaseFileEmitter.Emit(transports, "/api/conduit", "/conduit");

        // Assert
        result.Should().Contain("export class HttpTransport implements ConduitTransport");
    }

    [TestMethod]
    public void EmitHttpErrorHandling()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("if (!response.ok)");
        result.Should().Contain("Conduit dispatch failed with status");
    }

    [TestMethod]
    public void EmitAutoGeneratedHeader()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().StartWith("// Auto-generated by Conduit.TypeGen - do not edit");
    }

    [TestMethod]
    public void EmitSignalRTransportOptionsInterface()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export interface SignalRTransportOptions {");
        result.Should().Contain("accessTokenFactory?: () => string | Promise<string>;");
        result.Should().Contain("automaticReconnect?: boolean;");
        result.Should().Contain("retryPolicy?: IRetryPolicy;");
        result.Should().Contain("configure?: (builder: HubConnectionBuilder) => void;");
    }

    [TestMethod]
    public void EmitSignalRTransportConstructorWithPathOrConnection()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain(
            "constructor(pathOrConnection: string | HubConnection = '/conduit', options?: SignalRTransportOptions) {");
        result.Should().Contain("if (typeof pathOrConnection === 'string') {");
    }

    [TestMethod]
    public void EmitSignalRTransportWiringAccessTokenFactoryIntoWithUrl()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain(
            ".withUrl(pathOrConnection, { accessTokenFactory: options?.accessTokenFactory });");
        result.Should().Contain("if (options?.automaticReconnect !== false) builder.withAutomaticReconnect(options?.retryPolicy ?? DEFAULT_RETRY_POLICY);");
        result.Should().Contain("options?.configure?.(builder);");
        result.Should().Contain("this.connection = builder.build();");
    }

    [TestMethod]
    public void EmitSignalRTransportUsingProvidedHubConnectionAsIs()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("this.connection = pathOrConnection;");
    }

    [TestMethod]
    public void EmitSignalRTransportLazyResilientConnect()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("private started?: Promise<void>;");
        result.Should().Contain("connect(): Promise<void> {");
        result.Should().Contain("this.started = this.connection.start().catch(e => { this.started = undefined; throw e; });");
        result.Should().Contain("return this.started;");
    }

    [TestMethod]
    public void EmitSignalRTransportMethodsAwaitingConnect()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("await this.connect();");
    }

    [TestMethod]
    public void PreserveSignalRWireProtocol()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain(
            "return await this.connection.invoke<DispatchResult<TResult>>('Dispatch', type, payload, null, headers ?? null);");
        result.Should().Contain("await this.connection.invoke('Publish', type, data, null, headers ?? null);");
        result.Should().Contain("this.connection.on(eventName, handler);");
        result.Should().Contain("return { unsubscribe: () => this.connection.off(eventName, handler) };");
    }

    // B1: an unattended screen must recover from an outage of any length. SignalR's stock
    // withAutomaticReconnect() schedule stops for good after about 42 seconds, so the default is a policy.
    [TestMethod]
    public void EmitAnUnboundedDefaultRetryPolicy()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export const DEFAULT_RETRY_POLICY: IRetryPolicy = {");
        result.Should().Contain("const schedule = [0, 2000, 5000, 10000, 30000];");
        result.Should().Contain("return schedule[Math.min(retryContext.previousRetryCount, schedule.length - 1)] ?? 30000;");
        result.Should().NotContain("builder.withAutomaticReconnect();");
    }

    // B1: connect() trusted a resolved start forever, so a connection that closed for good wedged every
    // later dispatch. Text only -- ManagementSystem's signalr-transport.spec.ts pins the behavior.
    [TestMethod]
    public void EmitSignalRTransportRestartingADisconnectedConnection()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("if (this.started && this.connection.state === HubConnectionState.Disconnected) {");
    }
}
