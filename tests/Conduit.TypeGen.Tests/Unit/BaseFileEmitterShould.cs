    [TestMethod]
    public void PreserveSignalRWireProtocol()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain(
            "return await this.connection.invoke<DispatchResult<TResult>>('Dispatch', type, payload, null, headers ?? null);");
        result.Should().Contain("await this.connection.invoke('Publish', type, data, null, headers ?? null);");
        result.Should().Contain("this.connection.on(eventName, handler);");
        result.Should().Contain("return { unsubscribe: () => this.connection.off(eventName, handler) };");
    }

    // B1: an unattended screen must recover from an outage of any length. SignalR's stock
    // withAutomaticReconnect() schedule stops for good after about 42 seconds, so the default is a policy.
    [TestMethod]
    public void EmitAnUnboundedDefaultRetryPolicy()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export const DEFAULT_RETRY_POLICY: IRetryPolicy = {");
        result.Should().Contain("const schedule = [0, 2000, 5000, 10000, 30000];");
        result.Should().Contain("return schedule[Math.min(retryContext.previousRetryCount, schedule.length - 1)] ?? 30000;");
        result.Should().NotContain("builder.withAutomaticReconnect();");
    }

    // B1: connect() trusted a resolved start forever, so a connection that closed for good wedged every
    // later dispatch. Text only -- ManagementSystem's signalr-transport.spec.ts pins the behavior.
    [TestMethod]
    public void EmitSignalRTransportRestartingADisconnectedConnection()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("if (this.started && this.connection.state === HubConnectionState.Disconnected) {");
    }

    // The five states a consumer presents. 'stopped' is what lets an app tell a logout from an outage.
    [TestMethod]
    public void EmitTheTransportConnectionStateUnion()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain(
            "export type TransportConnectionState = 'stopped' | 'connecting' | 'connected' | 'reconnecting' | 'disconnected';");
    }

    // A late subscriber is told the current state at once, rather than waiting for the next change.
    [TestMethod]
    public void EmitOnStateChangeReplayingTheCurrentState()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("onStateChange(handler: (state: TransportConnectionState) => void): Subscription {");
        result.Should().Contain("handler(this.connectionState);");
    }

    // All three hub lifecycle hooks must report, or a consumer never hears about an outage.
    [TestMethod]
    public void EmitSignalRTransportReportingEveryHubLifecycleHook()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("this.connection.onreconnecting(() => this.setConnectionState('reconnecting'));");
        result.Should().Contain("this.connection.onreconnected(() => this.reportConnected());");
        result.Should().Contain("this.connection.onclose(error => {");
    }

    // stop() is intentional (logout, re-login, device re-attest), so the close it causes must not read as a loss.
    [TestMethod]
    public void EmitSignalRTransportReportingAnIntentionalStopAsStopped()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("this.setConnectionState('stopped');");
        result.Should().Contain("if (this.connectionState === 'stopped') return;");
    }

    [TestMethod]
    public void EmitSignalRTransportReportingConnectingAndConnectedAroundAStart()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("if (this.connectionState !== 'reconnecting') this.setConnectionState('connecting');");
        result.Should().Contain(".then(() => { this.reportConnected(); })");
        // What reportConnected() does, not just that it is called: a start that succeeded records the
        // connection (both fields) and reports it. Without this the body is unpinned here.
        result.Should().Contain("  private reportConnected(): void {");
        result.Should().Contain("    this.hasConnected = true;");
        result.Should().Contain("    this.connectedAt = Date.now();");
        result.Should().Contain("    this.setConnectionState('connected');");
    }

    // 4.4a: SignalR's own reconnect covers only a drop, or a close the server allowed a reconnect after. A close
    // without allowReconnect used to end in 'disconnected', where nothing retried until the next dispatch.
    [TestMethod]
    public void EmitSignalRTransportSchedulingARestartAfterACloseNobodyAskedFor()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("this.connection.onclose(error => {");
        result.Should().Contain("if (this.connectionState === 'stopped') return;");
        result.Should().Contain("this.scheduleRestart(error);");
    }

    // The waits come from the same policy the hub reconnects with: one schedule, one option, for both paths.
    [TestMethod]
    public void EmitRestartsThatWaitOnTheRetryPolicy()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("this.restartPolicy = options?.retryPolicy ?? DEFAULT_RETRY_POLICY;");
        result.Should().Contain("const delay = this.restartPolicy.nextRetryDelayInMilliseconds({");
        result.Should().Contain("previousRetryCount: this.restartAttempt,");
        result.Should().Contain("}, delay);");
    }

    // A server that accepts a connection and closes it at once must be retried on the schedule, not in a loop.
    [TestMethod]
    public void EmitABackoffThatResetsOnlyAfterAStableConnection()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("private static readonly STABLE_CONNECTION_MS = 30000;");
        result.Should().Contain(
            "if (this.connectedAt !== 0 && Date.now() - this.connectedAt >= SignalRTransport.STABLE_CONNECTION_MS) {");
    }

    // 'disconnected' survives for the apps that asked for it: opted out of reconnects, or a policy that gave up.
    [TestMethod]
    public void EmitDisconnectedOnlyWhenNothingIsRetrying()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("if (!this.restartsEnabled) { this.setConnectionState('disconnected'); return; }");
        result.Should().Contain("if (delay === null) { this.setConnectionState('disconnected'); return; }");
    }

    // Both entry points cancel a pending restart: an intentional stop, and a dispatch during a wait. Counted by
    // splitting rather than matched with a line break, because the emitter writes Environment.NewLine.
    [TestMethod]
    public void EmitRestartsThatAreCancelledByStopAndByADispatch()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("  private cancelRestart(): void {");
        result.Should().Contain("clearTimeout(this.restartTimer);");
        // stop() also forgets the schedule -- a logout is not an outage, so the next start begins at 0 s.
        result.Should().Contain("    this.restartAttempt = 0;");
        result.Should().Contain("    this.connectedAt = 0;");
        result.Split("this.cancelRestart();").Length.Should().Be(3);
    }

    // HttpTransport has no connection to report on. Widening the shared interface would force it to lie.
    [TestMethod]
    public void KeepConnectionStateOffTheSharedTransportInterface()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        var start = result.IndexOf("export interface ConduitTransport {", StringComparison.Ordinal);
        var transportInterface = result[start..result.IndexOf('}', start)];
        transportInterface.Should().NotContain("onStateChange");
    }

    // Registering the handler must not start the connection: a consumer registers it at construction, before anyone has
    // signed in, and the hub requires authorization. A handler registered early still hears the first connect.
    [TestMethod]
    public void EmitOnServerInfoWithoutStartingTheConnection()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export interface ConduitServerInfo {");
        var start = result.IndexOf(
            "  onServerInfo(handler: (info: ConduitServerInfo) => void): Subscription {", StringComparison.Ordinal);
        start.Should().BeGreaterThan(-1);
        var body = result[start..result.IndexOf("\n  }", start, StringComparison.Ordinal)];
        body.Should().Contain("this.connection.on('ConduitServerInfo', handler);");
        body.Should().NotContain("connect()");
    }

    // HttpTransport has no connection, so the handler stays off the shared interface.
    [TestMethod]
    public void KeepServerInfoOffTheSharedTransportInterface()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        var start = result.IndexOf("export interface ConduitTransport {", StringComparison.Ordinal);
        var transportInterface = result[start..result.IndexOf('}', start)];
        transportInterface.Should().NotContain("onServerInfo");
    }
