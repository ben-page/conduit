    [TestMethod]
    public void EmitSignalRTransportWhenExplicitlyIncluded()
    {
        // Arrange
        var transports = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "Http", "SignalR" };

        // Act
        var result = BaseFileEmitter.Emit(transports, "/api/conduit", "/conduit");

        // Assert
        result.Should().Contain("export class SignalRTransport");
        result.Should().Contain("import { HubConnectionBuilder, HubConnection, HubConnectionState }");
    }

    [TestMethod]
    public void OmitSignalRTransportWhenHttpOnly()
    {
