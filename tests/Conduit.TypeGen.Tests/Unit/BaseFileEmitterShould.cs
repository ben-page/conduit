using AwesomeAssertions;

namespace Conduit.TypeGen.Tests.Unit;

[TestClass]
public class BaseFileEmitterShould
{
    [TestMethod]
    public void EmitDispatchResultInterface()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export interface DispatchResult<T>");
        result.Should().Contain("data?: T;");
        result.Should().Contain("error?: ConduitError;");
    }

    [TestMethod]
    public void EmitConduitErrorInterfaces()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export interface ConduitError");
        result.Should().Contain("export interface ConduitErrorDetail");
    }

    [TestMethod]
    public void EmitConduitTransportInterface()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export interface ConduitTransport");
        result.Should().Contain("sendRequest<TResult>(type: string, payload: unknown): Promise<DispatchResult<TResult>>;");
        result.Should().Contain("sendEvent(type: string, data: unknown): Promise<void>;");
        result.Should().Contain("subscribe(eventName: string, handler: (data: unknown) => void): Subscription;");
    }

    [TestMethod]
    public void EmitSubscriptionInterface()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export interface Subscription");
        result.Should().Contain("unsubscribe(): void;");
    }

    [TestMethod]
    public void EmitHttpTransportByDefault()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("export class HttpTransport implements ConduitTransport");
        result.Should().Contain("async sendRequest<TResult>");
        result.Should().Contain("async sendEvent(");
    }

    [TestMethod]
    public void EmitSignalRTransportByDefault()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("import { HubConnection } from '@microsoft/signalr';");
        result.Should().Contain("export class SignalRTransport implements ConduitTransport");
    }

    [TestMethod]
    public void EmitSignalRTransportWhenExplicitlyIncluded()
    {
        // Arrange
        var transports = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "Http", "SignalR" };

        // Act
        var result = BaseFileEmitter.Emit(transports);

        // Assert
        result.Should().Contain("export class SignalRTransport");
        result.Should().Contain("import { HubConnection }");
    }

    [TestMethod]
    public void OmitSignalRTransportWhenHttpOnly()
    {
        // Arrange
        var transports = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "Http" };

        // Act
        var result = BaseFileEmitter.Emit(transports);

        // Assert
        result.Should().NotContain("export class SignalRTransport");
        result.Should().NotContain("@microsoft/signalr");
        result.Should().NotContain("HubConnection");
    }

    [TestMethod]
    public void AlwaysEmitHttpTransport()
    {
        // Arrange
        var transports = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "Http" };

        // Act
        var result = BaseFileEmitter.Emit(transports);

        // Assert
        result.Should().Contain("export class HttpTransport implements ConduitTransport");
    }

    [TestMethod]
    public void EmitHttpErrorHandling()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().Contain("if (!response.ok)");
        result.Should().Contain("Conduit dispatch failed with status");
    }

    [TestMethod]
    public void EmitAutoGeneratedHeader()
    {
        // Act
        var result = BaseFileEmitter.Emit();

        // Assert
        result.Should().StartWith("// Auto-generated by Conduit.TypeGen - do not edit");
    }
}
