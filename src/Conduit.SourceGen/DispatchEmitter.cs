using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Conduit.Analysis;

namespace Conduit.SourceGen;

/// <summary>
/// Emits the <c>ConduitDispatch</c> partial class with typed dispatch extension methods
/// (ExecuteAsync, FetchAsync, PublishAsync) for each discovered message type.
/// </summary>
public static class DispatchEmitter
{
    /// <summary>
    /// Generates the dispatch extension methods source code.
    /// </summary>
    /// <param name="types">All discovered dispatchable types.</param>
    /// <param name="handlers">All discovered handler registrations.</param>
    public static string Emit(
        IReadOnlyList<DispatchableTypeInfo> types,
        IReadOnlyList<HandlerInfo> handlers)
    {
        if (types is null)
        {
            throw new ArgumentNullException(nameof(types));
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine($"using {EmitConstants.NamespaceConfiguration};");
        sb.AppendLine($"using {EmitConstants.NamespaceRuntime};");
        sb.AppendLine();
        sb.AppendLine($"namespace {EmitConstants.NamespaceGenerated};");
        sb.AppendLine();
        sb.AppendLine("[System.CodeDom.Compiler.GeneratedCode(\"Conduit.SourceGen\", \"1.0.0\")]");
        sb.AppendLine("internal static class ConduitDispatch");
        sb.AppendLine("{");

        foreach (var type in types)
        {
            var handler = handlers.FirstOrDefault(h => h.MessageFullTypeName == type.FullTypeName);
            if (handler == null)
            {
                continue;
            }

            switch (type.Kind)
            {
                case DispatchableKind.Command:
                    EmitCommandWithResult(sb, type, handler);
                    break;
                case DispatchableKind.VoidCommand:
                    if (type.IsFireAndForget)
                    {
                        EmitFireAndForgetVoidCommand(sb, type, handler);
                    }
                    else
                    {
                        EmitVoidCommand(sb, type, handler);
                    }

                    break;
                case DispatchableKind.Query:
                    EmitQuery(sb, type, handler);
                    break;
                case DispatchableKind.Event:
                case DispatchableKind.Model:
                default:
                    break;
            }
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitCommandWithResult(
        StringBuilder sb,
        DispatchableTypeInfo type,
        HandlerInfo handler)
    {
        var typeRef = EmitConstants.ToCSharpTypeRef(type.FullTypeName);
        sb.AppendLine($"    public static async Task<{type.ResultFullTypeName}> Execute(");
        EmitDispatchParameters(sb, typeRef, "command");
        sb.AppendLine("    {");
        EmitAttemptsCall(sb, typeRef, type.ResultFullTypeName!, "ExecuteAttempt", "command", isVoidAttempt: false, returnsResult: true);
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine($"    private static async Task<{type.ResultFullTypeName}> ExecuteAttempt(");
        EmitDispatchParameters(sb, typeRef, "command");
        sb.AppendLine("    {");
        EmitHandlerAndBehaviorBody(
            sb, type, handler, isVoid: false,
            validateCall: $"(({EmitConstants.ICommand}<{type.ResultFullTypeName}>)command).Validate();");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitVoidCommand(
        StringBuilder sb,
        DispatchableTypeInfo type,
        HandlerInfo handler)
    {
        var typeRef = EmitConstants.ToCSharpTypeRef(type.FullTypeName);
        sb.AppendLine($"    public static async Task Execute(");
        EmitDispatchParameters(sb, typeRef, "command");
        sb.AppendLine("    {");
        EmitAttemptsCall(sb, typeRef, "object", "ExecuteAttempt", "command", isVoidAttempt: true, returnsResult: false);
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine($"    private static async Task ExecuteAttempt(");
        EmitDispatchParameters(sb, typeRef, "command");
        sb.AppendLine("    {");
        EmitHandlerAndBehaviorBody(
            sb, type, handler, isVoid: true,
            validateCall: $"(({EmitConstants.ICommand})command).Validate();");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine($"    public static async Task<object?> ExecuteVoid(");
        sb.AppendLine($"        {typeRef} command,");
        sb.AppendLine($"        IServiceProvider serviceProvider,");
        sb.AppendLine($"        ConduitOptions conduitOptions,");
        sb.AppendLine($"        CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine($"        await Execute(command, serviceProvider, conduitOptions, cancellationToken);");
        sb.AppendLine($"        return {EmitConstants.Unit}.Value;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitQuery(
        StringBuilder sb,
        DispatchableTypeInfo type,
        HandlerInfo handler)
    {
        var typeRef = EmitConstants.ToCSharpTypeRef(type.FullTypeName);
        sb.AppendLine($"    public static async Task<{type.ResultFullTypeName}> Fetch(");
        EmitDispatchParameters(sb, typeRef, "query");
        sb.AppendLine("    {");
        EmitAttemptsCall(sb, typeRef, type.ResultFullTypeName!, "FetchAttempt", "query", isVoidAttempt: false, returnsResult: true);
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine($"    private static async Task<{type.ResultFullTypeName}> FetchAttempt(");
        EmitDispatchParameters(sb, typeRef, "query");
        sb.AppendLine("    {");
        EmitHandlerAndBehaviorBody(
            sb, type, handler, isVoid: false,
            validateCall: $"(({EmitConstants.IQuery}<{type.ResultFullTypeName}>)query).Validate();");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitFireAndForgetVoidCommand(
        StringBuilder sb,
        DispatchableTypeInfo type,
        HandlerInfo _)
    {
        var typeRef = EmitConstants.ToCSharpTypeRef(type.FullTypeName);
        var handlerInterface =
            $"{EmitConstants.NamespaceHandlers}.ICommandHandler<{typeRef}>";

        // Execute method: runs pipeline in caller context, enqueues handler to background dispatcher
        sb.AppendLine($"    public static Task Execute(");
        sb.AppendLine($"        {typeRef} command,");
        sb.AppendLine($"        IServiceProvider serviceProvider,");
        sb.AppendLine($"        ConduitOptions conduitOptions,");
        sb.AppendLine($"        CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var behaviors = {EmitConstants.ConduitRuntime}.ResolvePipelines<{typeRef}, object>(conduitOptions, serviceProvider);");
        sb.AppendLine($"        var dispatcher = serviceProvider.GetRequiredService<ConduitBackgroundDispatcher>();");
        sb.AppendLine($"        var scopeFactory = serviceProvider.GetRequiredService<IServiceScopeFactory>();");
        sb.AppendLine();
        sb.AppendLine($"        // The handler call enqueues to the background dispatcher instead of executing inline.");
        sb.AppendLine($"        // Pipeline behaviors wrap this — they run in the caller context, the handler runs in the background.");
        sb.AppendLine($"        Func<Task<object>> handlerCall = () =>");
        sb.AppendLine("        {");
        EmitValidateInnermost(sb, $"(({EmitConstants.ICommand})command).Validate();");
        sb.AppendLine($"            dispatcher.Enqueue(async ct =>");
        sb.AppendLine("            {");
        sb.AppendLine($"                // Background work runs after the caller's DI scope is disposed — resolve from a fresh scope.");
        sb.AppendLine($"                using var scope = scopeFactory.CreateScope();");
        sb.AppendLine($"                var handler = scope.ServiceProvider.GetRequiredService<{handlerInterface}>();");
        sb.AppendLine($"                await handler.HandleAsync(command, ct);");
        sb.AppendLine("            });");
        sb.AppendLine($"            return Task.FromResult<object?>({EmitConstants.Unit}.Value)!;");
        sb.AppendLine("        };");
        sb.AppendLine();
        sb.AppendLine($"        return {EmitConstants.ConduitRuntime}.ExecuteWithBehaviors(command, behaviors, handlerCall, cancellationToken);");
        sb.AppendLine("    }");
        sb.AppendLine();

        // ExecuteVoid wrapper (for wire dispatch compatibility — local callers use background dispatch)
        sb.AppendLine($"    public static async Task<object?> ExecuteVoid(");
        sb.AppendLine($"        {typeRef} command,");
        sb.AppendLine($"        IServiceProvider serviceProvider,");
        sb.AppendLine($"        ConduitOptions conduitOptions,");
        sb.AppendLine($"        CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine($"        await Execute(command, serviceProvider, conduitOptions, cancellationToken);");
        sb.AppendLine($"        return {EmitConstants.Unit}.Value;");
        sb.AppendLine("    }");
        sb.AppendLine();

        // ExecuteVoidWire — inline handler execution for wire-inbound dispatch.
        // Wire dispatch already provides fire-and-forget semantics (no reply), so the handler
        // must run inline within the DI scope. Using the background dispatcher here would cause
        // the handler to execute after the scope is disposed. It runs handlers, so it goes through
        // the dispatch boundary (still answering the wire with Unit); the local Execute above only
        // enqueues, so it does not.
        sb.AppendLine($"    public static async Task<object?> ExecuteVoidWire(");
        EmitDispatchParameters(sb, typeRef, "command");
        sb.AppendLine("    {");
        EmitAttemptsCall(sb, typeRef, "object", "ExecuteVoidWireAttempt", "command", isVoidAttempt: true, returnsResult: true);
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine($"    private static async Task ExecuteVoidWireAttempt(");
        EmitDispatchParameters(sb, typeRef, "command");
        sb.AppendLine("    {");
        sb.AppendLine($"        var behaviors = {EmitConstants.ConduitRuntime}.ResolvePipelines<{typeRef}, object>(conduitOptions, serviceProvider);");
        sb.AppendLine($"        Func<Task<object>> handlerCall = () =>");
        sb.AppendLine("        {");
        EmitValidateInnermost(sb, $"(({EmitConstants.ICommand})command).Validate();");
        sb.AppendLine($"            var handler = serviceProvider.GetRequiredService<{handlerInterface}>();");
        sb.AppendLine($"            return {EmitConstants.ConduitRuntime}.VoidToObject(() => handler.HandleAsync(command, cancellationToken));");
        sb.AppendLine("        };");
        sb.AppendLine($"        await {EmitConstants.ConduitRuntime}.ExecuteWithBehaviors(command, behaviors, handlerCall, cancellationToken);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    /// <summary>
    /// Emits the four parameters every <c>ConduitDispatch</c> method takes: the request, the dispatching provider, the
    /// options and the token.
    /// </summary>
    private static void EmitDispatchParameters(StringBuilder sb, string typeRef, string requestParamName)
    {
        sb.AppendLine($"        {typeRef} {requestParamName},");
        sb.AppendLine($"        IServiceProvider serviceProvider,");
        sb.AppendLine($"        ConduitOptions conduitOptions,");
        sb.AppendLine($"        CancellationToken cancellationToken)");
    }

    /// <summary>
    /// Emits a handler-running method's body: a call to <c>ConduitRuntime.DispatchAttemptsAsync</c> that runs
    /// <paramref name="attemptMethod"/> (the method's pipeline and handler) over each attempt's provider.
    /// </summary>
    /// <remarks>
    /// Without a retry policy, nested in an attempt, or not covered, the boundary runs the attempt once on
    /// <c>serviceProvider</c> itself, so the dispatch behaves exactly as if the body were inline. A void attempt's
    /// result is <c>Unit</c>; the explicit type arguments make the lambda a <c>Task&lt;object&gt;</c>.
    /// </remarks>
    private static void EmitAttemptsCall(
        StringBuilder sb,
        string typeRef,
        string resultType,
        string attemptMethod,
        string requestParamName,
        bool isVoidAttempt,
        bool returnsResult)
    {
        var attemptCall = $"{attemptMethod}({requestParamName}, attemptServices, conduitOptions, cancellationToken)";
        var awaitBoundary = returnsResult ? "return await" : "await";
        if (isVoidAttempt)
        {
            sb.AppendLine($"        {awaitBoundary} {EmitConstants.ConduitRuntime}.DispatchAttemptsAsync<{typeRef}, {resultType}>(");
            sb.AppendLine("            serviceProvider,");
            sb.AppendLine("            async attemptServices =>");
            sb.AppendLine("            {");
            sb.AppendLine($"                await {attemptCall};");
            sb.AppendLine($"                return (object){EmitConstants.Unit}.Value;");
            sb.AppendLine("            },");
            sb.AppendLine("            cancellationToken);");
        }
        else
        {
            sb.AppendLine($"        {awaitBoundary} {EmitConstants.ConduitRuntime}.DispatchAttemptsAsync<{typeRef}, {resultType}>(");
            sb.AppendLine("            serviceProvider,");
            sb.AppendLine($"            attemptServices => {attemptCall},");
            sb.AppendLine("            cancellationToken);");
        }
    }

    private static void EmitHandlerAndBehaviorBody(
        StringBuilder sb,
        DispatchableTypeInfo type,
        HandlerInfo handler,
        bool isVoid,
        string validateCall)
    {
        var requestParamName = type.Kind == DispatchableKind.Query ? "query" : "command";
        var resultType = isVoid ? "object" : type.ResultFullTypeName;
        var typeRef = EmitConstants.ToCSharpTypeRef(type.FullTypeName);

        var handlerInterface = type.Kind switch
        {
            DispatchableKind.Command =>
                $"{EmitConstants.NamespaceHandlers}.ICommandHandler<{typeRef}, {type.ResultFullTypeName}>",
            DispatchableKind.VoidCommand =>
                $"{EmitConstants.NamespaceHandlers}.ICommandHandler<{typeRef}>",
            DispatchableKind.Query =>
                $"{EmitConstants.NamespaceHandlers}.IQueryHandler<{typeRef}, {type.ResultFullTypeName}>",
            DispatchableKind.Event or DispatchableKind.Model or _ => handler.HandlerFullTypeName,
        };

        sb.AppendLine($"        var behaviors = {EmitConstants.ConduitRuntime}.ResolvePipelines<{typeRef}, {resultType}>(conduitOptions, serviceProvider);");
        sb.AppendLine();

        if (isVoid)
        {
            sb.AppendLine($"        Func<Task<object>> handlerCall = () =>");
            sb.AppendLine("        {");
            EmitValidateInnermost(sb, validateCall);
            sb.AppendLine($"            var handler = serviceProvider.GetRequiredService<{handlerInterface}>();");
            sb.AppendLine($"            return {EmitConstants.ConduitRuntime}.VoidToObject(() => handler.HandleAsync({requestParamName}, cancellationToken));");
            sb.AppendLine("        };");
        }
        else
        {
            sb.AppendLine($"        Func<Task<{resultType}>> handlerCall = () =>");
            sb.AppendLine("        {");
            EmitValidateInnermost(sb, validateCall);
            sb.AppendLine($"            var handler = serviceProvider.GetRequiredService<{handlerInterface}>();");
            sb.AppendLine($"            return handler.HandleAsync({requestParamName}, cancellationToken);");
            sb.AppendLine("        };");
        }

        sb.AppendLine();

        if (isVoid)
        {
            sb.AppendLine($"        await {EmitConstants.ConduitRuntime}.ExecuteWithBehaviors({requestParamName}, behaviors, handlerCall, cancellationToken);");
        }
        else
        {
            sb.AppendLine($"        return await {EmitConstants.ConduitRuntime}.ExecuteWithBehaviors({requestParamName}, behaviors, handlerCall, cancellationToken);");
        }
    }

    /// <summary>
    /// Emits a message's <c>Validate()</c> call as the first statement of the <c>handlerCall</c> lambda.
    /// </summary>
    /// <remarks>
    /// Validate() runs INNERMOST -- after every behavior, immediately before the handler (or the fire-and-forget
    /// enqueue, still on the caller's thread), so a behavior that refuses (authorization) never runs the caller's
    /// input. Every path still validates; nothing is opt-in.
    /// </remarks>
    private static void EmitValidateInnermost(StringBuilder sb, string validateCall)
    {
        sb.AppendLine($"            {validateCall}");
    }
}
