using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Conduit.Analysis;

namespace Conduit.SourceGen;

public static class DispatchEmitter
{
    public static string Emit(
        IReadOnlyList<DispatchableTypeInfo> types,
        IReadOnlyList<HandlerInfo> handlers,
        IReadOnlyList<BehaviorInfo>? behaviors = null)
    {
        if (types is null)
        {
            throw new ArgumentNullException(nameof(types));
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine();
        sb.AppendLine("namespace Conduit.Generated;");
        sb.AppendLine();
        sb.AppendLine("[System.CodeDom.Compiler.GeneratedCode(\"Conduit.SourceGen\", \"1.0.0\")]");
        sb.AppendLine("internal static class ConduitDispatch");
        sb.AppendLine("{");

        foreach (var type in types)
        {
            var handler = handlers.FirstOrDefault(h => h.CommandFullTypeName == type.FullTypeName);
            if (handler == null)
            {
                continue;
            }

            switch (type.Kind)
            {
                case DispatchableKind.Command:
                    EmitCommandWithResult(sb, type, handler, behaviors);
                    break;
                case DispatchableKind.VoidCommand:
                    EmitVoidCommand(sb, type, handler, behaviors);
                    break;
                case DispatchableKind.Query:
                    EmitQuery(sb, type, handler, behaviors);
                    break;
                case DispatchableKind.Event:
                default:
                    break;
            }
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitCommandWithResult(
        StringBuilder sb,
        DispatchableTypeInfo type,
        HandlerInfo handler,
        IReadOnlyList<BehaviorInfo>? behaviors)
    {
        sb.AppendLine($"    public static async Task<{type.ResultFullTypeName}> Execute(");
        sb.AppendLine($"        {type.FullTypeName} command,");
        sb.AppendLine($"        IServiceProvider serviceProvider,");
        sb.AppendLine($"        CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine($"        ((Conduit.Messages.ICommand<{type.ResultFullTypeName}>)command).Validate();");
        EmitHandlerAndBehaviorBody(sb, type, handler, behaviors, isVoid: false);
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitVoidCommand(
        StringBuilder sb,
        DispatchableTypeInfo type,
        HandlerInfo handler,
        IReadOnlyList<BehaviorInfo>? behaviors)
    {
        // Void commands need both Execute (returns Task) and ExecuteVoid (for wire dispatch returning Task<object?>)
        sb.AppendLine($"    public static async Task Execute(");
        sb.AppendLine($"        {type.FullTypeName} command,");
        sb.AppendLine($"        IServiceProvider serviceProvider,");
        sb.AppendLine($"        CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine("        ((Conduit.Messages.ICommand)command).Validate();");
        EmitHandlerAndBehaviorBody(sb, type, handler, behaviors, isVoid: true);
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine($"    public static async Task<object?> ExecuteVoid(");
        sb.AppendLine($"        {type.FullTypeName} command,");
        sb.AppendLine($"        IServiceProvider serviceProvider,");
        sb.AppendLine($"        CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine($"        await Execute(command, serviceProvider, cancellationToken);");
        sb.AppendLine("        return null;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitQuery(
        StringBuilder sb,
        DispatchableTypeInfo type,
        HandlerInfo handler,
        IReadOnlyList<BehaviorInfo>? behaviors)
    {
        sb.AppendLine($"    public static async Task<{type.ResultFullTypeName}> Fetch(");
        sb.AppendLine($"        {type.FullTypeName} query,");
        sb.AppendLine($"        IServiceProvider serviceProvider,");
        sb.AppendLine($"        CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine($"        ((Conduit.Messages.IQuery<{type.ResultFullTypeName}>)query).Validate();");
        EmitHandlerAndBehaviorBody(sb, type, handler, behaviors, isVoid: false);
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitHandlerAndBehaviorBody(
        StringBuilder sb,
        DispatchableTypeInfo type,
        HandlerInfo handler,
        IReadOnlyList<BehaviorInfo>? behaviors,
        bool isVoid)
    {
        var applicableBehaviors = behaviors?
            .Where(b => !b.IsEventBehavior)
            .OrderBy(b => b.Order)
            .ToList() ?? new List<BehaviorInfo>();

        var requestParamName = type.Kind == DispatchableKind.Query ? "query" : "command";

        if (applicableBehaviors.Count == 0)
        {
            sb.AppendLine($"        var handler = serviceProvider.GetRequiredService<{handler.HandlerFullTypeName}>();");
            if (isVoid)
            {
                sb.AppendLine($"        await handler.HandleAsync({requestParamName}, cancellationToken);");
            }
            else
            {
                sb.AppendLine($"        return await handler.HandleAsync({requestParamName}, cancellationToken);");
            }
        }
        else
        {
            // Emit behavior and handler resolution
            for (var i = 0; i < applicableBehaviors.Count; i++)
            {
                var behavior = applicableBehaviors[i];
                var behaviorTypeName = MakeBehaviorTypeName(behavior, type, isVoid);
                sb.AppendLine($"        var behavior{i + 1} = serviceProvider.GetRequiredService<{behaviorTypeName}>();");
            }

            sb.AppendLine($"        var handler = serviceProvider.GetRequiredService<{handler.HandlerFullTypeName}>();");
            sb.AppendLine();

            // Build nested call
            var innerCall = $"handler.HandleAsync({requestParamName}, cancellationToken)";

            for (var i = applicableBehaviors.Count - 1; i >= 0; i--)
            {
                var capturedInner = innerCall;
                innerCall = $"behavior{i + 1}.HandleAsync({requestParamName},\n            () => {capturedInner},\n            cancellationToken)";
            }

            if (isVoid)
            {
                sb.AppendLine($"        await {innerCall};");
            }
            else
            {
                sb.AppendLine($"        return await {innerCall};");
            }
        }
    }

    private static string MakeBehaviorTypeName(BehaviorInfo behavior, DispatchableTypeInfo type, bool isVoid)
    {
        if (isVoid)
        {
            // Void commands use behaviors differently - they'd need a different shape
            // For now, use the open generic with the command type and a dummy result
            return $"{behavior.OpenTypeName}<{type.FullTypeName}, object>";
        }

        return $"{behavior.OpenTypeName}<{type.FullTypeName}, {type.ResultFullTypeName}>";
    }
}

public sealed class HandlerInfo
{
    public required string CommandFullTypeName { get; init; }
    public required string HandlerFullTypeName { get; init; }
}

public sealed class BehaviorInfo
{
    public required string OpenTypeName { get; init; }
    public required int Order { get; init; }
    public required bool IsEventBehavior { get; init; }
}
