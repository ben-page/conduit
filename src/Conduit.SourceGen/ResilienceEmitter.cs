using System.Collections.Generic;
using System.Text;
using Conduit.Analysis;

namespace Conduit.SourceGen;

/// <summary>
/// Emits the <c>ConduitResilienceDispatch</c> class with a compile-time type switch
/// that resolves Polly pipeline keys by message type.
/// Only emitted when the compilation references Conduit.Resilience.
/// </summary>
public static class ResilienceEmitter
{
    /// <summary>
    /// Generates the resilience dispatch source code.
    /// </summary>
    /// <param name="types">All discovered dispatchable types.</param>
    public static string Emit(IReadOnlyList<DispatchableTypeInfo> types)
    {
        if (types is null)
        {
            throw new System.ArgumentNullException(nameof(types));
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine();
        sb.AppendLine("namespace Conduit.Generated;");
        sb.AppendLine();
        sb.AppendLine("[System.CodeDom.Compiler.GeneratedCode(\"Conduit.SourceGen\", \"1.0.0\")]");
        sb.AppendLine("internal static class ConduitResilienceDispatch");
        sb.AppendLine("{");
        sb.AppendLine("    public static string? ResolveResiliencePipelineKey<TRequest>()");
        sb.AppendLine("    {");
        sb.AppendLine("        return typeof(TRequest) switch");
        sb.AppendLine("        {");

        foreach (var type in types)
        {
            if (type.Kind == DispatchableKind.Model)
            {
                continue; // Skip non-dispatchable types
            }

            // typeof needs the C# ('.') form; the returned discriminator is the metadata ('+') form.
            sb.AppendLine($"            Type t when t == typeof({EmitConstants.ToCSharpTypeRef(type.FullTypeName)}) => \"{type.FullTypeName}\",");
        }

        sb.AppendLine("            _ => null,");
        sb.AppendLine("        };");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }
}
