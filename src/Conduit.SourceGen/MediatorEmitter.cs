using System.Collections.Generic;
using System.Linq;
using System.Text;
using Conduit.Analysis;

namespace Conduit.SourceGen;

/// <summary>
/// Emits the <c>ConduitMediator</c> class implementing <c>IWireMediator</c>.
/// Contains the dispatch switch for commands/queries, event publishing with listener invocation,
/// and wire dispatch methods for inbound transport messages.
/// </summary>
public static class MediatorEmitter
{
    /// <summary>
    /// Generates the mediator implementation source code.
    /// </summary>
    /// <param name="types">All discovered dispatchable types.</param>
    /// <param name="handlers">All discovered handler registrations.</param>
    public static string Emit(
        IReadOnlyList<DispatchableTypeInfo> types,
        IReadOnlyList<HandlerInfo> handlers)
    {
        var handledTypes = new HashSet<string>(handlers.Select(h => h.MessageFullTypeName));
        var commands = types.Where(t => t.Kind == DispatchableKind.Command).ToList();
        var voidCommands = types.Where(t => t.Kind == DispatchableKind.VoidCommand).ToList();
        var queries = types.Where(t => t.Kind == DispatchableKind.Query).ToList();
        var events = types.Where(t => t.Kind == DispatchableKind.Event).ToList();

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Diagnostics;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine("using System.Text.Json;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine("using Microsoft.Extensions.Logging;");
        sb.AppendLine("using Conduit;");
        sb.AppendLine($"using {EmitConstants.NamespaceConfiguration};");
        sb.AppendLine($"using {EmitConstants.NamespaceRuntime};");
        sb.AppendLine($"using {EmitConstants.NamespaceMiddleware};");
        sb.AppendLine($"using {EmitConstants.NamespaceMessages};");
        sb.AppendLine($"using {EmitConstants.NamespaceHandlers};");
        sb.AppendLine();
        sb.AppendLine($"namespace {EmitConstants.NamespaceGenerated};");
        sb.AppendLine();
        sb.AppendLine("[System.CodeDom.Compiler.GeneratedCode(\"Conduit.SourceGen\", \"1.0.0\")]");
        sb.AppendLine("internal sealed class ConduitMediator(");
        sb.AppendLine("    IServiceProvider serviceProvider,");
        sb.AppendLine("    IEnumerable<IConduitTransport> transports,");
        sb.AppendLine("    IEnumerable<IInboundInterceptor> interceptors,");
        sb.AppendLine("    ConduitOptions conduitOptions,");
        sb.AppendLine($"    ILogger<ConduitMediator> logger) : IWireMediator, {EmitConstants.ILocalEnvelopeDispatcher}");
        sb.AppendLine("{");

        // Strongly-typed overloads for commands with result
        foreach (var cmd in commands)
        {
            var hasHandler = handledTypes.Contains(cmd.FullTypeName);

            // FullTypeName is the metadata ('+') wire discriminator; typeRef is its C# form for
            // type/generic/typeof positions (nested types join with '.').
            var typeRef = EmitConstants.ToCSharpTypeRef(cmd.FullTypeName);

            // Thin delegating overload (no configure parameter)
            sb.AppendLine($"    public async Task<{cmd.ResultFullTypeName}> ExecuteAsync(");
            sb.AppendLine($"        {typeRef} command,");
            sb.AppendLine($"        CancellationToken cancellationToken = default)");
            sb.AppendLine($"        => await ExecuteAsync(command, null, cancellationToken);");
            sb.AppendLine();

            // Full implementation with DispatchOptions
            sb.AppendLine($"    public async Task<{cmd.ResultFullTypeName}> ExecuteAsync(");
            sb.AppendLine($"        {typeRef} command,");
            sb.AppendLine($"        Action<{EmitConstants.DispatchOptions}>? configure,");
            sb.AppendLine($"        CancellationToken cancellationToken = default)");
            sb.AppendLine("    {");
            EmitContextStart(sb, $"\"{cmd.FullTypeName}\"", "command",
                emitPayloadCapture: true, requestVarName: "command",
                requestTypeName: typeRef, isDoNotAudit: cmd.IsDoNotAudit);
            sb.AppendLine($"            var endpoint = ConduitRuntime.ResolveRoute(conduitOptions, \"{cmd.FullTypeName}\");");
            sb.AppendLine("            if (endpoint != null)");
            sb.AppendLine("            {");
            sb.AppendLine($"                ConduitRuntime.LogRouteDispatch(logger, \"{cmd.FullTypeName}\", endpoint.Name);");
            sb.AppendLine($"                __activity?.SetTag(\"conduit.dispatch\", \"remote\");");
            sb.AppendLine($"                __activity?.SetTag(\"conduit.endpoint\", endpoint.Name);");
            sb.AppendLine($"                var transport = ConduitRuntime.ResolveTransport(serviceProvider, endpoint);");
            sb.AppendLine($"                var payload = JsonSerializer.SerializeToElement(command, ConduitRuntime.JsonOptions);");
            sb.AppendLine($"                var result = await transport.SendRequestAsync(");
            sb.AppendLine($"                    new DispatchEnvelope(\"{cmd.FullTypeName}\", payload), cancellationToken);");
            EmitDispatchCompleted(sb, "                ");
            sb.AppendLine($"                return result is JsonElement je");
            sb.AppendLine($"                    ? JsonSerializer.Deserialize<{cmd.ResultFullTypeName}>(je, ConduitRuntime.JsonOptions)!");
            sb.AppendLine($"                    : ({cmd.ResultFullTypeName})result!;");
            sb.AppendLine("            }");

            if (hasHandler)
            {
                sb.AppendLine($"            ConduitRuntime.LogLocalDispatch(logger, \"{cmd.FullTypeName}\");");
                sb.AppendLine($"            __activity?.SetTag(\"conduit.dispatch\", \"local\");");
                sb.AppendLine($"            var __handlerResult = await ConduitDispatch.Execute(command, serviceProvider, conduitOptions, cancellationToken);");
                EmitDispatchCompleted(sb, "            ");
                sb.AppendLine($"            return __handlerResult;");
            }
            else
            {
                sb.AppendLine($"            throw new InvalidOperationException(\"No local handler for {cmd.FullTypeName} and no route matched.\");");
            }

            EmitContextEnd(sb);
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        // Strongly-typed overloads for void commands
        foreach (var cmd in voidCommands)
        {
            var hasHandler = handledTypes.Contains(cmd.FullTypeName);
            var typeRef = EmitConstants.ToCSharpTypeRef(cmd.FullTypeName);

            // Thin delegating overload (no configure parameter)
            sb.AppendLine($"    public async Task ExecuteAsync(");
            sb.AppendLine($"        {typeRef} command,");
            sb.AppendLine($"        CancellationToken cancellationToken = default)");
            sb.AppendLine($"        => await ExecuteAsync(command, null, cancellationToken);");
            sb.AppendLine();

            // Full implementation with DispatchOptions
            sb.AppendLine($"    public async Task ExecuteAsync(");
            sb.AppendLine($"        {typeRef} command,");
            sb.AppendLine($"        Action<{EmitConstants.DispatchOptions}>? configure,");
            sb.AppendLine($"        CancellationToken cancellationToken = default)");
            sb.AppendLine("    {");
            EmitContextStart(sb, $"\"{cmd.FullTypeName}\"", "command",
                emitPayloadCapture: true, requestVarName: "command",
                requestTypeName: typeRef, isDoNotAudit: cmd.IsDoNotAudit);
            sb.AppendLine($"            var endpoint = ConduitRuntime.ResolveRoute(conduitOptions, \"{cmd.FullTypeName}\");");
            sb.AppendLine("            if (endpoint != null)");
            sb.AppendLine("            {");
            sb.AppendLine($"                var payload = JsonSerializer.SerializeToElement(command, ConduitRuntime.JsonOptions);");
            sb.AppendLine($"                var envelope = new DispatchEnvelope(\"{cmd.FullTypeName}\", payload);");

            if (cmd.IsFireAndForget && !cmd.IsFireAndForgetImmediate)
            {
                // Non-Immediate F&F commands can be captured by the outbox for post-commit delivery.
                // On capture (true) we return; on decline (no transaction) or absence we fall through
                // to the direct transport send below. Immediate F&F commands skip capture entirely.
                sb.AppendLine($"                var outboundInterceptor = serviceProvider.GetService<{EmitConstants.IOutboundInterceptor}>();");
                sb.AppendLine("                if (outboundInterceptor != null && outboundInterceptor.Intercept(envelope))");
                sb.AppendLine("                {");
                EmitDispatchCompleted(sb, "                    ");
                sb.AppendLine("                    return;");
                sb.AppendLine("                }");
                sb.AppendLine();
            }

            sb.AppendLine($"                ConduitRuntime.LogRouteDispatch(logger, \"{cmd.FullTypeName}\", endpoint.Name);");
            sb.AppendLine($"                __activity?.SetTag(\"conduit.dispatch\", \"remote\");");
            sb.AppendLine($"                __activity?.SetTag(\"conduit.endpoint\", endpoint.Name);");
            sb.AppendLine($"                var transport = ConduitRuntime.ResolveTransport(serviceProvider, endpoint);");

            if (cmd.IsFireAndForget)
            {
                // F&F commands use the event path -- no reply expected
                sb.AppendLine($"                await transport.SendEventAsync(envelope, cancellationToken);");
            }
            else
            {
                // Non-F&F void commands use request/response to confirm handler execution
                sb.AppendLine($"                await transport.SendRequestAsync(envelope, cancellationToken);");
            }

            EmitDispatchCompleted(sb, "                ");
            sb.AppendLine("                return;");
            sb.AppendLine("            }");

            if (hasHandler)
            {
                sb.AppendLine($"            ConduitRuntime.LogLocalDispatch(logger, \"{cmd.FullTypeName}\");");
                sb.AppendLine($"            __activity?.SetTag(\"conduit.dispatch\", \"local\");");
                sb.AppendLine($"            await ConduitDispatch.Execute(command, serviceProvider, conduitOptions, cancellationToken);");
                EmitDispatchCompleted(sb, "            ");
            }
            else
            {
                sb.AppendLine($"            throw new InvalidOperationException(\"No local handler for {cmd.FullTypeName} and no route matched.\");");
            }

            EmitContextEnd(sb);
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        // Strongly-typed overloads for queries
        foreach (var query in queries)
        {
            var hasHandler = handledTypes.Contains(query.FullTypeName);
            var typeRef = EmitConstants.ToCSharpTypeRef(query.FullTypeName);

            // Thin delegating overload (no configure parameter)
            sb.AppendLine($"    public async Task<{query.ResultFullTypeName}> FetchAsync(");
            sb.AppendLine($"        {typeRef} query,");
            sb.AppendLine($"        CancellationToken cancellationToken = default)");
            sb.AppendLine($"        => await FetchAsync(query, null, cancellationToken);");
            sb.AppendLine();

            // Full implementation with DispatchOptions
            sb.AppendLine($"    public async Task<{query.ResultFullTypeName}> FetchAsync(");
            sb.AppendLine($"        {typeRef} query,");
            sb.AppendLine($"        Action<{EmitConstants.DispatchOptions}>? configure,");
            sb.AppendLine($"        CancellationToken cancellationToken = default)");
            sb.AppendLine("    {");
            EmitContextStart(sb, $"\"{query.FullTypeName}\"", "query",
                emitPayloadCapture: true, requestVarName: "query",
                requestTypeName: typeRef, isDoNotAudit: query.IsDoNotAudit);
            sb.AppendLine($"            var endpoint = ConduitRuntime.ResolveRoute(conduitOptions, \"{query.FullTypeName}\");");
            sb.AppendLine("            if (endpoint != null)");
            sb.AppendLine("            {");
            sb.AppendLine($"                ConduitRuntime.LogRouteDispatch(logger, \"{query.FullTypeName}\", endpoint.Name);");
            sb.AppendLine($"                __activity?.SetTag(\"conduit.dispatch\", \"remote\");");
            sb.AppendLine($"                __activity?.SetTag(\"conduit.endpoint\", endpoint.Name);");
            sb.AppendLine($"                var transport = ConduitRuntime.ResolveTransport(serviceProvider, endpoint);");
            sb.AppendLine($"                var payload = JsonSerializer.SerializeToElement(query, ConduitRuntime.JsonOptions);");
            sb.AppendLine($"                var result = await transport.SendRequestAsync(");
            sb.AppendLine($"                    new DispatchEnvelope(\"{query.FullTypeName}\", payload), cancellationToken);");
            EmitDispatchCompleted(sb, "                ");
            sb.AppendLine($"                return result is JsonElement je");
            sb.AppendLine($"                    ? JsonSerializer.Deserialize<{query.ResultFullTypeName}>(je, ConduitRuntime.JsonOptions)!");
            sb.AppendLine($"                    : ({query.ResultFullTypeName})result!;");
            sb.AppendLine("            }");

            if (hasHandler)
            {
                sb.AppendLine($"            ConduitRuntime.LogLocalDispatch(logger, \"{query.FullTypeName}\");");
                sb.AppendLine($"            __activity?.SetTag(\"conduit.dispatch\", \"local\");");
                sb.AppendLine($"            var __handlerResult = await ConduitDispatch.Fetch(query, serviceProvider, conduitOptions, cancellationToken);");
                EmitDispatchCompleted(sb, "            ");
                sb.AppendLine($"            return __handlerResult;");
            }
            else
            {
                sb.AppendLine($"            throw new InvalidOperationException(\"No local handler for {query.FullTypeName} and no route matched.\");");
            }

            EmitContextEnd(sb);
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        // Generic interface fallback for ICommand<TResult>
        EmitGenericCommandFallback(sb, commands);

        // Void command interface fallback
        EmitVoidCommandFallback(sb, voidCommands);

        // Query interface fallback
        EmitQueryFallback(sb, queries);

        // PublishAsync
        EmitPublishAsync(sb, events);

        // Wire dispatch (private, called by HandleWireRequestAsync)
        EmitWireDispatch(sb, commands, voidCommands, queries, handledTypes);

        // Wire publish (private, called by HandleWireEventAsync)
        EmitWirePublish(sb, events);

        // Local envelope dispatcher (ILocalEnvelopeDispatcher: classification + envelope redelivery)
        EmitLocalEnvelopeDispatcher(sb, events);

        // HandleWireRequestAsync -- delegates to ConduitRuntime
        sb.AppendLine("    public Task<DispatchResult<object>> HandleWireRequestAsync(");
        sb.AppendLine("        DispatchEnvelope envelope,");
        sb.AppendLine("        CancellationToken cancellationToken)");
        sb.AppendLine("        => ConduitRuntime.HandleWireRequest(envelope.Type, interceptors, () => envelope, DispatchRequestAsync, logger, serviceProvider.GetServices<Conduit.Runtime.IWireExceptionTranslator>(), cancellationToken);");
        sb.AppendLine();

        // HandleWireEventAsync -- delegates to ConduitRuntime
        sb.AppendLine("    public Task HandleWireEventAsync(");
        sb.AppendLine("        DispatchEnvelope envelope,");
        sb.AppendLine("        CancellationToken cancellationToken)");
        sb.AppendLine("        => ConduitRuntime.HandleWireEvent(envelope.Type, interceptors, () => envelope, DispatchEventAsync, logger, cancellationToken);");

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitGenericCommandFallback(StringBuilder sb, List<DispatchableTypeInfo> commands)
    {
        // Parameterless overload delegates to configure overload
        sb.AppendLine("    Task<TResult> IMediator.ExecuteAsync<TResult>(");
        sb.AppendLine("        ICommand<TResult> command,");
        sb.AppendLine("        CancellationToken cancellationToken)");
        sb.AppendLine($"        => ((IMediator)this).ExecuteAsync(command, null, cancellationToken);");
        sb.AppendLine();

        // Configure overload with type switch
        sb.AppendLine($"    Task<TResult> IMediator.ExecuteAsync<TResult>(");
        sb.AppendLine($"        ICommand<TResult> command,");
        sb.AppendLine($"        Action<{EmitConstants.DispatchOptions}>? configure,");
        sb.AppendLine($"        CancellationToken cancellationToken)");
        sb.AppendLine("        => command switch");
        sb.AppendLine("        {");

        foreach (var cmd in commands)
        {
            sb.AppendLine($"            {EmitConstants.ToCSharpTypeRef(cmd.FullTypeName)} cmd => ConduitRuntime.CastTask<{cmd.ResultFullTypeName}, TResult>(ExecuteAsync(cmd, configure, cancellationToken)),");
        }

        sb.AppendLine("            _ => throw new InvalidOperationException($\"No handler for {command.GetType().Name}\")");
        sb.AppendLine("        };");
        sb.AppendLine();
    }

