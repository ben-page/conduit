    private static void EmitPublishAsync(
        StringBuilder sb,
        IReadOnlyList<ListenerGroup> listenerGroups,
        List<DispatchableTypeInfo> events)
    {
        var localOnlyTypes = new HashSet<string>(
            events.Where(e => e.IsLocalOnly).Select(e => e.FullTypeName));
        var fireAndForgetTypes = new HashSet<string>(
            events.Where(e => e.IsFireAndForget).Select(e => e.FullTypeName));

        // PublishAsync dispatches to local listeners AND broadcasts to all registered transports.
        // Events marked [LocalOnly] skip the broadcast step entirely.
        // Events marked [FireAndForget] enqueue everything to the background dispatcher.
        // Catches EventListenerException — local publish is fire-and-forget.
        sb.AppendLine("    public async Task PublishAsync(IEvent @event, CancellationToken cancellationToken = default)");
        sb.AppendLine("    {");

        EmitContextStart(sb, "@event.GetType().FullName!", "event");

        // F&F events enqueue local listeners to background dispatcher instead of running inline.
        // Transport broadcast still happens inline — events are already fire-and-forget on the wire.
        if (fireAndForgetTypes.Count > 0)
        {
            sb.AppendLine("        if (@event is " + string.Join(" or ", fireAndForgetTypes) + ")");
            sb.AppendLine("        {");
            sb.AppendLine("            var dispatcher = serviceProvider.GetRequiredService<ConduitBackgroundDispatcher>();");
            sb.AppendLine("            var captured = @event;");
            sb.AppendLine("            dispatcher.Enqueue(async ct =>");
            sb.AppendLine("            {");
            sb.AppendLine("                try");
            sb.AppendLine("                {");
            sb.AppendLine("                    await PublishLocalAsync(captured, ct);");
            sb.AppendLine("                }");
            sb.AppendLine($"                catch ({EmitConstants.NamespaceExceptions}.EventListenerException ex)");
            sb.AppendLine("                {");
            sb.AppendLine("                    logger.LogError(ex, \"One or more event listeners failed for {EventType}\", captured.GetType().FullName);");
            sb.AppendLine("                }");
            sb.AppendLine("            });");
            sb.AppendLine("        }");
            sb.AppendLine("        else");
            sb.AppendLine("        {");
        }

        // Non-F&F events run local listeners inline
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine("            await PublishLocalAsync(@event, cancellationToken);");
        sb.AppendLine("        }");
        sb.AppendLine($"        catch ({EmitConstants.NamespaceExceptions}.EventListenerException ex)");
        sb.AppendLine("        {");
        sb.AppendLine("            logger.LogError(ex, \"One or more event listeners failed for {EventType}\", @event.GetType().FullName);");
        sb.AppendLine("        }");

        if (fireAndForgetTypes.Count > 0)
        {
            sb.AppendLine("        }");
        }

        sb.AppendLine();

        if (localOnlyTypes.Count == events.Count)
        {
            // All events are local-only — no broadcast needed
        }
        else if (localOnlyTypes.Count == 0)
        {
            // No local-only events — always broadcast
            EmitBroadcastBlock(sb);
        }
        else
        {
            // Mix of local-only and broadcastable — check type at runtime
            sb.AppendLine("        var shouldBroadcast = @event switch");
            sb.AppendLine("        {");
            foreach (var localOnly in localOnlyTypes)
            {
                sb.AppendLine($"            {localOnly} => false,");
            }

            sb.AppendLine("            _ => true,");
            sb.AppendLine("        };");
            sb.AppendLine();
            sb.AppendLine("        if (shouldBroadcast)");
            sb.AppendLine("        {");
            EmitBroadcastBlock(sb, indent: "    ");
            sb.AppendLine("        }");
        }

        EmitContextEnd(sb);
        sb.AppendLine("    }");
        sb.AppendLine();

        // PublishLocalAsync dispatches only to local listeners (no transport broadcast).
        // Used by DispatchEventAsync for wire-inbound events to prevent echo loops.
        // Uses the unified IPipelineBehavior<TEvent, object> pipeline (same as commands/queries).
        // Throws EventListenerException if any listener failed (all listeners still run).
        if (listenerGroups.Count == 0)
        {
            sb.AppendLine("    private Task PublishLocalAsync(IEvent @event, CancellationToken cancellationToken)");
            sb.AppendLine("    {");
            sb.AppendLine("        return Task.CompletedTask;");
            sb.AppendLine("    }");
            sb.AppendLine();
            return;
        }

        sb.AppendLine("    private async Task PublishLocalAsync(IEvent @event, CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine("        var exceptions = new List<Exception>();");
        sb.AppendLine("        switch (@event)");
        sb.AppendLine("        {");

        foreach (var group in listenerGroups)
        {
            sb.AppendLine($"            case {group.EventFullTypeName} e:");
            sb.AppendLine($"            {{");

            // Build the innermost delegate: resolve all listeners by interface, iterate with try/catch
            sb.AppendLine($"                Func<Task<object>> listenerChain = async () =>");
            sb.AppendLine($"                {{");
            sb.AppendLine($"                    var listeners = serviceProvider.GetServices<{EmitConstants.NamespaceHandlers}.IEventListener<{group.EventFullTypeName}>>();");
            sb.AppendLine($"                    foreach (var listener in listeners)");
            sb.AppendLine($"                    {{");
            sb.AppendLine($"                        try");
            sb.AppendLine($"                        {{");
            sb.AppendLine($"                            await listener.HandleAsync(e, cancellationToken);");
            sb.AppendLine($"                        }}");
            sb.AppendLine($"                        catch (Exception ex)");
            sb.AppendLine($"                        {{");
            sb.AppendLine($"                            ConduitRuntime.LogListenerFailure(logger, listener.GetType().Name, ex);");
            sb.AppendLine($"                            exceptions.Add(ex);");
            sb.AppendLine($"                        }}");
            sb.AppendLine($"                    }}");

            sb.AppendLine($"                    return {EmitConstants.Unit}.Value;");
            sb.AppendLine($"                }};");
            sb.AppendLine();

            // Wrap with unified pipeline behaviors via ConduitRuntime
            sb.AppendLine($"                var behaviors = ConduitRuntime.ResolvePipelines<{group.EventFullTypeName}, object>(conduitOptions, serviceProvider);");
            sb.AppendLine($"                await ConduitRuntime.ExecuteWithBehaviors(e, behaviors, listenerChain, cancellationToken);");

            sb.AppendLine("                break;");
            sb.AppendLine($"            }}");
        }

        sb.AppendLine("        }");
        sb.AppendLine("        if (exceptions.Count > 0)");
        sb.AppendLine("        {");
        sb.AppendLine("            throw new Conduit.Exceptions.EventListenerException(");
        sb.AppendLine("                $\"One or more listeners failed for event '{@event.GetType().FullName}'. See logs for details.\",");
        sb.AppendLine("                exceptions);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitBroadcastBlock(StringBuilder sb, string indent = "")
    {
        sb.AppendLine($"        {indent}var eventEnvelope = new DispatchEnvelope(");
        sb.AppendLine($"        {indent}    @event.GetType().FullName!,");
        sb.AppendLine($"        {indent}    JsonSerializer.SerializeToElement(@event, @event.GetType(), ConduitRuntime.JsonOptions));");
        sb.AppendLine($"        {indent}var outboundInterceptor = serviceProvider.GetService<{EmitConstants.IOutboundInterceptor}>();");
        sb.AppendLine($"        {indent}if (outboundInterceptor != null)");
        sb.AppendLine($"        {indent}{{");
        sb.AppendLine($"        {indent}    outboundInterceptor.Intercept(eventEnvelope);");
        sb.AppendLine($"        {indent}}}");
        sb.AppendLine($"        {indent}else");
        sb.AppendLine($"        {indent}{{");
        sb.AppendLine($"        {indent}    var transportList = transports.ToArray();");
        sb.AppendLine($"        {indent}    ConduitRuntime.LogBroadcast(logger, eventEnvelope.Type, transportList.Length);");
        sb.AppendLine($"        {indent}    foreach (var transport in transportList)");
        sb.AppendLine($"        {indent}    {{");
        sb.AppendLine($"        {indent}        try");
        sb.AppendLine($"        {indent}        {{");
        sb.AppendLine($"        {indent}            await transport.SendEventAsync(eventEnvelope, cancellationToken);");
        sb.AppendLine($"        {indent}        }}");
        sb.AppendLine($"        {indent}        catch (Exception ex)");
        sb.AppendLine($"        {indent}        {{");
        sb.AppendLine($"        {indent}            ConduitRuntime.LogListenerFailure(logger, transport.GetType().Name, ex);");
        sb.AppendLine($"        {indent}        }}");
        sb.AppendLine($"        {indent}    }}");
        sb.AppendLine($"        {indent}}}");
    }

    private static void EmitWireDispatch(
        StringBuilder sb,
        List<DispatchableTypeInfo> commands,
        List<DispatchableTypeInfo> voidCommands,
        List<DispatchableTypeInfo> queries,
        HashSet<string> handledTypes)
    {
        sb.AppendLine("    private async Task<object?> DispatchRequestAsync(");
        sb.AppendLine("        string type,");
        sb.AppendLine("        JsonElement payload,");
        sb.AppendLine("        CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine("        // Forward to transport if the type matches a route (handles types not known locally)");
        sb.AppendLine("        var endpoint = ConduitRuntime.ResolveRoute(conduitOptions, type);");
        sb.AppendLine("        if (endpoint != null)");
        sb.AppendLine("        {");
        sb.AppendLine("            ConduitRuntime.LogWireForward(logger, type, endpoint.Name);");
        sb.AppendLine("            var transport = ConduitRuntime.ResolveTransport(serviceProvider, endpoint);");
        sb.AppendLine("            var result = await transport.SendRequestAsync(");
        sb.AppendLine("                new DispatchEnvelope(type, payload), cancellationToken);");
        sb.AppendLine("            return result;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        return type switch");
        sb.AppendLine("        {");

        foreach (var cmd in commands.Where(c => handledTypes.Contains(c.FullTypeName)))
        {
            sb.AppendLine($"            \"{cmd.FullTypeName}\" => await ConduitDispatch.Execute(");
            sb.AppendLine($"                JsonSerializer.Deserialize<{cmd.FullTypeName}>(payload, ConduitRuntime.JsonOptions)!,");
            sb.AppendLine($"                serviceProvider,");
            sb.AppendLine($"                conduitOptions,");
            sb.AppendLine($"                cancellationToken),");
        }

        foreach (var cmd in voidCommands.Where(c => handledTypes.Contains(c.FullTypeName)))
        {
            // F&F void commands use ExecuteVoidWire (inline handler) to avoid scope lifetime issues.
            // The background dispatcher path would execute after the DI scope is disposed.
            var method = cmd.IsFireAndForget ? "ExecuteVoidWire" : "ExecuteVoid";
            sb.AppendLine($"            \"{cmd.FullTypeName}\" => await ConduitDispatch.{method}(");
            sb.AppendLine($"                JsonSerializer.Deserialize<{cmd.FullTypeName}>(payload, ConduitRuntime.JsonOptions)!,");
            sb.AppendLine($"                serviceProvider,");
            sb.AppendLine($"                conduitOptions,");
            sb.AppendLine($"                cancellationToken),");
        }

        foreach (var query in queries.Where(q => handledTypes.Contains(q.FullTypeName)))
        {
            sb.AppendLine($"            \"{query.FullTypeName}\" => await ConduitDispatch.Fetch(");
            sb.AppendLine($"                JsonSerializer.Deserialize<{query.FullTypeName}>(payload, ConduitRuntime.JsonOptions)!,");
            sb.AppendLine($"                serviceProvider,");
            sb.AppendLine($"                conduitOptions,");
            sb.AppendLine($"                cancellationToken),");
        }

        sb.AppendLine("            _ => throw new InvalidOperationException($\"Unknown dispatch type: {type}\")");
        sb.AppendLine("        };");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitWirePublish(StringBuilder sb, List<DispatchableTypeInfo> events)
    {
        sb.AppendLine("    private async Task DispatchEventAsync(");
        sb.AppendLine("        string type,");
        sb.AppendLine("        JsonElement payload,");
        sb.AppendLine("        CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine("        IEvent @event = type switch");
        sb.AppendLine("        {");

        foreach (var evt in events)
        {
            sb.AppendLine($"            \"{evt.FullTypeName}\" => JsonSerializer.Deserialize<{evt.FullTypeName}>(payload, ConduitRuntime.JsonOptions)!,");
        }

        sb.AppendLine("            _ => throw new InvalidOperationException($\"Unknown event type: {type}\")");
        sb.AppendLine("        };");
        sb.AppendLine("        await PublishLocalAsync(@event, cancellationToken);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitContextStart(StringBuilder sb, string messageTypeExpr, string messageKind)
    {
