    private static void EmitPublishAsync(
        StringBuilder sb,
        List<DispatchableTypeInfo> events)
    {
        // These are used in C# type-pattern positions, so use the C# ('.') form for nested types.
        var localOnlyTypes = new HashSet<string>(
            events.Where(e => e.IsLocalOnly).Select(e => EmitConstants.ToCSharpTypeRef(e.FullTypeName)));
        var fireAndForgetTypes = new HashSet<string>(
            events.Where(e => e.IsFireAndForget).Select(e => EmitConstants.ToCSharpTypeRef(e.FullTypeName)));

        // Capturable = non-Immediate F&F events. These are offered to the outbox interceptor BEFORE
        // any local enqueue: on capture the whole publish body is skipped (post-commit delivery).
        // Immediate F&F events are excluded here (they must deliver at publish time) but stay in
        // fireAndForgetTypes for the background local-enqueue and the broadcast-bypass flag.
        var capturableTypes = new HashSet<string>(events
            .Where(e => e.IsFireAndForget && !e.IsFireAndForgetImmediate)
            .Select(e => EmitConstants.ToCSharpTypeRef(e.FullTypeName)));

        // Thin delegating overload (no configure parameter)
        sb.AppendLine("    public async Task PublishAsync(IEvent @event, CancellationToken cancellationToken = default)");
        sb.AppendLine("        => await PublishAsync(@event, null, cancellationToken);");
        sb.AppendLine();

        // Full implementation with DispatchOptions
        sb.AppendLine($"    public async Task PublishAsync(IEvent @event, Action<{EmitConstants.DispatchOptions}>? configure, CancellationToken cancellationToken = default)");
        sb.AppendLine("    {");

        EmitContextStart(sb, "@event.GetType().FullName!", "event",
            emitPayloadCapture: true, requestVarName: "@event",
            requestTypeName: null, isDoNotAudit: false);

        // Transaction-gated outbox capture: offer non-Immediate F&F events to the interceptor before
        // any local enqueue or broadcast. On capture (true) the entire publish body is skipped -- the
        // outbox re-delivers post-commit (transport + local listeners). On decline (no transaction) or
        // absence, __captured stays false and the publish proceeds exactly as without an interceptor.
        if (capturableTypes.Count > 0)
        {
            sb.AppendLine("        var __captured = false;");
            sb.AppendLine("        if (@event is " + string.Join(" or ", capturableTypes) + ")");
            sb.AppendLine("        {");
            sb.AppendLine($"            var __outboundInterceptor = serviceProvider.GetService<{EmitConstants.IOutboundInterceptor}>();");
            sb.AppendLine("            if (__outboundInterceptor != null)");
            sb.AppendLine("            {");
            sb.AppendLine("                var __captureEnvelope = new DispatchEnvelope(");
            sb.AppendLine("                    @event.GetType().FullName!,");
            sb.AppendLine("                    JsonSerializer.SerializeToElement(@event, @event.GetType(), ConduitRuntime.JsonOptions));");
            sb.AppendLine("                __captured = __outboundInterceptor.Intercept(__captureEnvelope);");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine("        if (!__captured)");
            sb.AppendLine("        {");
        }

        // F&F events enqueue local listeners to background dispatcher instead of running inline.
        // Transport broadcast still happens inline -- events are already fire-and-forget on the wire.
        if (fireAndForgetTypes.Count > 0)
        {
            sb.AppendLine("        if (@event is " + string.Join(" or ", fireAndForgetTypes) + ")");
            sb.AppendLine("        {");
            sb.AppendLine("            var dispatcher = serviceProvider.GetRequiredService<ConduitBackgroundDispatcher>();");
            sb.AppendLine("            var scopeFactory = serviceProvider.GetRequiredService<IServiceScopeFactory>();");
            sb.AppendLine("            var captured = @event;");
            sb.AppendLine("            dispatcher.Enqueue(async ct =>");
            sb.AppendLine("            {");
            sb.AppendLine("                // Fire-and-forget runs after the publishing request's DI scope is disposed,");
            sb.AppendLine("                // so resolve listeners from a fresh scope rather than the captured (disposed) one.");
            sb.AppendLine("                using var scope = scopeFactory.CreateScope();");
            sb.AppendLine("                try");
            sb.AppendLine("                {");
            sb.AppendLine("                    await PublishLocalAsync(scope.ServiceProvider, captured, ct);");
            sb.AppendLine("                }");
            sb.AppendLine($"                catch ({EmitConstants.NamespaceExceptions}.EventListenerException ex)");
            sb.AppendLine("                {");
            sb.AppendLine("                    logger.LogError(ex, \"One or more event listeners failed for {EventType}\", captured.GetType().FullName);");
            sb.AppendLine("                }");
            sb.AppendLine("            });");
            sb.AppendLine("        }");
            sb.AppendLine("        else");
            sb.AppendLine("        {");
        }

        // Non-F&F events run local listeners inline
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine("            await PublishLocalAsync(serviceProvider, @event, cancellationToken);");
        sb.AppendLine("        }");
        sb.AppendLine($"        catch ({EmitConstants.NamespaceExceptions}.EventListenerException ex)");
        sb.AppendLine("        {");
        sb.AppendLine("            logger.LogError(ex, \"One or more event listeners failed for {EventType}\", @event.GetType().FullName);");
        sb.AppendLine("        }");

        if (fireAndForgetTypes.Count > 0)
        {
            sb.AppendLine("        }");
        }

        sb.AppendLine();

        if (localOnlyTypes.Count == events.Count)
        {
            // All events are local-only -- no broadcast needed
        }
        else if (localOnlyTypes.Count == 0)
        {
            // No local-only events -- always broadcast
            EmitBroadcastBlock(sb, fireAndForgetTypes);
        }
        else
        {
            // Mix of local-only and broadcastable -- check type at runtime
            sb.AppendLine("        var shouldBroadcast = @event switch");
            sb.AppendLine("        {");
            foreach (var localOnly in localOnlyTypes)
            {
                sb.AppendLine($"            {localOnly} => false,");
            }

            sb.AppendLine("            _ => true,");
            sb.AppendLine("        };");
            sb.AppendLine();
            sb.AppendLine("        if (shouldBroadcast)");
            sb.AppendLine("        {");
            EmitBroadcastBlock(sb, fireAndForgetTypes, indent: "    ");
            sb.AppendLine("        }");
        }

        // Close the capture guard opened after context-start: everything from the local enqueue
        // through broadcast is skipped when the interceptor captured the event.
        if (capturableTypes.Count > 0)
        {
            sb.AppendLine("        }");
        }

        EmitDispatchCompleted(sb, "        ");
        EmitContextEnd(sb);
        sb.AppendLine("    }");
        sb.AppendLine();

        // PublishLocalAsync dispatches only to local listeners (no transport broadcast).
        // Used by DispatchEventAsync for wire-inbound events to prevent echo loops.
        // Uses the unified IPipelineBehavior<TEvent, object> pipeline (same as commands/queries).
        // Throws EventListenerException if any listener failed (all listeners still run).
        //
        // A case is emitted for every event type, not only for those with a listener discovered at
        // compile time. Each case already resolves its listeners from the container, so gating the
        // cases on compile-time discovery would mean an event type could never gain a listener
        // registered at runtime -- which is how Conduit.Jobs wires an event trigger to a job.
        if (events.Count == 0)
        {
            sb.AppendLine("    private Task PublishLocalAsync(IServiceProvider serviceProvider, IEvent @event, CancellationToken cancellationToken)");
            sb.AppendLine("    {");
            sb.AppendLine("        return Task.CompletedTask;");
            sb.AppendLine("    }");
            sb.AppendLine();
            return;
        }

        sb.AppendLine("    private async Task PublishLocalAsync(IServiceProvider serviceProvider, IEvent @event, CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine("        var exceptions = new List<Exception>();");
        sb.AppendLine("        switch (@event)");
        sb.AppendLine("        {");

        foreach (var discoveredEvent in events)
        {
            var eventTypeRef = EmitConstants.ToCSharpTypeRef(discoveredEvent.FullTypeName);
            sb.AppendLine($"            case {eventTypeRef} e:");
            sb.AppendLine($"            {{");

            // Build the innermost delegate: resolve all listeners by interface, iterate with try/catch
            sb.AppendLine($"                Func<Task<object>> listenerChain = async () =>");
            sb.AppendLine($"                {{");
            sb.AppendLine($"                    var listeners = serviceProvider.GetServices<{EmitConstants.NamespaceHandlers}.IEventListener<{eventTypeRef}>>();");
            sb.AppendLine($"                    foreach (var listener in listeners)");
            sb.AppendLine($"                    {{");
            // Per-listener observations: HandlerStarted
            sb.AppendLine($"                        var __listenerType = listener.GetType().FullName ?? listener.GetType().Name;");
            sb.AppendLine($"                        {EmitConstants.MessageContext_Observe}(new {EmitConstants.HandlerStarted}(__listenerType));");
            sb.AppendLine($"                        var __listenerSw = Stopwatch.GetTimestamp();");
            sb.AppendLine($"                        try");
            sb.AppendLine($"                        {{");
            sb.AppendLine($"                            await listener.HandleAsync(e, cancellationToken);");
            // Per-listener observations: HandlerCompleted
            sb.AppendLine($"                            var __listenerElapsed = Stopwatch.GetElapsedTime(__listenerSw).TotalMilliseconds;");
            sb.AppendLine($"                            {EmitConstants.MessageContext_Observe}(new {EmitConstants.HandlerCompleted}(__listenerElapsed));");
            sb.AppendLine($"                        }}");
            sb.AppendLine($"                        catch (Exception ex)");
            sb.AppendLine($"                        {{");
            // Per-listener observations: HandlerFailed
            sb.AppendLine($"                            {EmitConstants.MessageContext_Observe}(new {EmitConstants.HandlerFailed}(ex.Message, ex.GetType().FullName ?? ex.GetType().Name));");
            sb.AppendLine($"                            ConduitRuntime.LogListenerFailure(logger, listener.GetType().Name, ex);");
            sb.AppendLine($"                            exceptions.Add(ex);");
            sb.AppendLine($"                        }}");
            sb.AppendLine($"                    }}");

            sb.AppendLine($"                    return {EmitConstants.Unit}.Value;");
            sb.AppendLine($"                }};");
            sb.AppendLine();

            // Wrap with unified pipeline behaviors via ConduitRuntime
            sb.AppendLine($"                var behaviors = ConduitRuntime.ResolvePipelines<{eventTypeRef}, object>(conduitOptions, serviceProvider);");
            sb.AppendLine($"                await ConduitRuntime.ExecuteWithBehaviors(e, behaviors, listenerChain, cancellationToken);");

            sb.AppendLine("                break;");
            sb.AppendLine($"            }}");
        }

        sb.AppendLine("        }");
        sb.AppendLine("        if (exceptions.Count > 0)");
        sb.AppendLine("        {");
        sb.AppendLine("            throw new Conduit.Exceptions.EventListenerException(");
        sb.AppendLine("                $\"One or more listeners failed for event '{@event.GetType().FullName}'. See logs for details.\",");
        sb.AppendLine("                exceptions);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitBroadcastBlock(StringBuilder sb, HashSet<string> fireAndForgetTypes, string indent = "")
    {
        sb.AppendLine($"        {indent}var eventEnvelope = new DispatchEnvelope(");
        sb.AppendLine($"        {indent}    @event.GetType().FullName!,");
        sb.AppendLine($"        {indent}    JsonSerializer.SerializeToElement(@event, @event.GetType(), ConduitRuntime.JsonOptions));");
        sb.AppendLine($"        {indent}var outboundInterceptor = serviceProvider.GetService<{EmitConstants.IOutboundInterceptor}>();");

        if (fireAndForgetTypes.Count > 0)
        {
            // Any F&F event reaching broadcast was either declined at the pre-enqueue capture attempt
            // (don't re-ask the interceptor) or is Immediate (never captured) -- bypass capture here.
            sb.AppendLine($"        {indent}var __bypassCapture = @event is " + string.Join(" or ", fireAndForgetTypes) + ";");
            sb.AppendLine($"        {indent}if (outboundInterceptor != null && !__bypassCapture && outboundInterceptor.Intercept(eventEnvelope))");
        }
        else
        {
            sb.AppendLine($"        {indent}if (outboundInterceptor != null && outboundInterceptor.Intercept(eventEnvelope))");
        }

        sb.AppendLine($"        {indent}{{");
        sb.AppendLine($"        {indent}    // Captured for post-commit transport delivery. Inline local listeners (plain events)");
        sb.AppendLine($"        {indent}    // already ran above, inside the ambient transaction -- flush will NOT re-run them.");
        sb.AppendLine($"        {indent}}}");
        sb.AppendLine($"        {indent}else");
        sb.AppendLine($"        {indent}{{");
        sb.AppendLine($"        {indent}    var transportList = transports.ToArray();");
        sb.AppendLine($"        {indent}    ConduitRuntime.LogBroadcast(logger, eventEnvelope.Type, transportList.Length);");
        sb.AppendLine($"        {indent}    foreach (var transport in transportList)");
        sb.AppendLine($"        {indent}    {{");
        sb.AppendLine($"        {indent}        try");
        sb.AppendLine($"        {indent}        {{");
        sb.AppendLine($"        {indent}            await transport.SendEventAsync(eventEnvelope, cancellationToken);");
        sb.AppendLine($"        {indent}        }}");
        sb.AppendLine($"        {indent}        catch (Exception ex)");
        sb.AppendLine($"        {indent}        {{");
        sb.AppendLine($"        {indent}            ConduitRuntime.LogListenerFailure(logger, transport.GetType().Name, ex);");
        sb.AppendLine($"        {indent}        }}");
        sb.AppendLine($"        {indent}    }}");
        sb.AppendLine($"        {indent}}}");
    }

    private static void EmitWireDispatch(
        StringBuilder sb,
        List<DispatchableTypeInfo> commands,
        List<DispatchableTypeInfo> voidCommands,
        List<DispatchableTypeInfo> queries,
        HashSet<string> handledTypes)
    {
        sb.AppendLine("    private async Task<object?> DispatchRequestAsync(");
        sb.AppendLine("        string type,");
        sb.AppendLine("        JsonElement payload,");
        sb.AppendLine("        CancellationToken cancellationToken)");
        sb.AppendLine("    {");

        EmitWireContextStart(sb, "type", "Request");

        sb.AppendLine("            // Forward to transport if the type matches a route (handles types not known locally)");
        sb.AppendLine("            var endpoint = ConduitRuntime.ResolveRoute(conduitOptions, type);");
        sb.AppendLine("            if (endpoint != null)");
        sb.AppendLine("            {");
        sb.AppendLine("                ConduitRuntime.LogWireForward(logger, type, endpoint.Name);");
        sb.AppendLine("                var transport = ConduitRuntime.ResolveTransport(serviceProvider, endpoint);");
        sb.AppendLine("                var result = await transport.SendRequestAsync(");
        sb.AppendLine("                    new DispatchEnvelope(type, payload), cancellationToken);");
        EmitDispatchCompleted(sb, "                ");
        sb.AppendLine("                return result;");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine("            object? __result = type switch");
        sb.AppendLine("            {");

        foreach (var cmd in commands.Where(c => handledTypes.Contains(c.FullTypeName)))
        {
            sb.AppendLine($"                \"{cmd.FullTypeName}\" => await ConduitDispatch.Execute(");
            sb.AppendLine($"                    {WireRead(cmd)},");
            sb.AppendLine($"                    serviceProvider,");
            sb.AppendLine($"                    conduitOptions,");
            sb.AppendLine($"                    cancellationToken),");
        }

        foreach (var cmd in voidCommands.Where(c => handledTypes.Contains(c.FullTypeName)))
        {
            // F&F void commands use ExecuteVoidWire (inline handler) to avoid scope lifetime issues.
            // The background dispatcher path would execute after the DI scope is disposed.
            var method = cmd.IsFireAndForget ? "ExecuteVoidWire" : "ExecuteVoid";
            sb.AppendLine($"                \"{cmd.FullTypeName}\" => await ConduitDispatch.{method}(");
            sb.AppendLine($"                    {WireRead(cmd)},");
            sb.AppendLine($"                    serviceProvider,");
            sb.AppendLine($"                    conduitOptions,");
            sb.AppendLine($"                    cancellationToken),");
        }

        foreach (var query in queries.Where(q => handledTypes.Contains(q.FullTypeName)))
        {
            sb.AppendLine($"                \"{query.FullTypeName}\" => await ConduitDispatch.Fetch(");
            sb.AppendLine($"                    {WireRead(query)},");
            sb.AppendLine($"                    serviceProvider,");
            sb.AppendLine($"                    conduitOptions,");
            sb.AppendLine($"                    cancellationToken),");
        }

        sb.AppendLine("                _ => throw new InvalidOperationException($\"Unknown dispatch type: {type}\")");
        sb.AppendLine("            };");

        EmitDispatchCompleted(sb, "            ");
        sb.AppendLine("            return __result;");

        EmitWireContextEnd(sb);
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitWirePublish(StringBuilder sb, List<DispatchableTypeInfo> events)
    {
        sb.AppendLine("    private async Task DispatchEventAsync(");
        sb.AppendLine("        string type,");
        sb.AppendLine("        JsonElement payload,");
        sb.AppendLine("        CancellationToken cancellationToken)");
        sb.AppendLine("    {");

        EmitWireContextStart(sb, "type", "Event");

        sb.AppendLine("            IEvent @event = type switch");
        sb.AppendLine("            {");

        foreach (var evt in events)
        {
            var read = $"JsonSerializer.Deserialize<{EmitConstants.ToCSharpTypeRef(evt.FullTypeName)}>(payload, ConduitRuntime.JsonOptions)!";
            var arm = evt.IsDoNotAudit ? read : $"ConduitRuntime.CaptureAuditPayload({read})";
            sb.AppendLine($"                \"{evt.FullTypeName}\" => {arm},");
        }

        sb.AppendLine("                _ => throw new InvalidOperationException($\"Unknown event type: {type}\")");
        sb.AppendLine("            };");
        sb.AppendLine("            await PublishLocalAsync(serviceProvider, @event, cancellationToken);");

        EmitDispatchCompleted(sb, "            ");

        EmitWireContextEnd(sb);
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    /// <summary>
    /// Emits the generated <c>ILocalEnvelopeDispatcher</c> implementation: classification switches
    /// consumed by the outbox's flush/relay delivery decisions, plus envelope-to-local-listener
    /// redelivery. Switch case keys are <see cref="DispatchableTypeInfo.FullTypeName"/> verbatim
    /// (metadata '+' form) -- the same strings <c>DispatchEnvelope.Type</c> carries at runtime.
    /// <c>ToCSharpTypeRef</c> is used only for the generic type argument in the deserialize call,
    /// never for the string case labels.
    /// </summary>
    private static void EmitLocalEnvelopeDispatcher(StringBuilder sb, List<DispatchableTypeInfo> events)
    {
        sb.AppendLine("    /// <inheritdoc />");
        sb.AppendLine("    public bool DeliversLocally(string messageType) => messageType switch");
        sb.AppendLine("    {");

        foreach (var evt in events.Where(e => e.IsFireAndForget && !e.IsFireAndForgetImmediate))
        {
            sb.AppendLine($"        \"{evt.FullTypeName}\" => true,");
        }

        sb.AppendLine("        _ => false,");
        sb.AppendLine("    };");
        sb.AppendLine();

        sb.AppendLine("    /// <inheritdoc />");
        sb.AppendLine("    public bool IsLocalOnly(string messageType) => messageType switch");
        sb.AppendLine("    {");

        foreach (var evt in events.Where(e => e.IsLocalOnly))
        {
            sb.AppendLine($"        \"{evt.FullTypeName}\" => true,");
        }

        sb.AppendLine("        _ => false,");
        sb.AppendLine("    };");
        sb.AppendLine();

        sb.AppendLine("    /// <inheritdoc />");
        sb.AppendLine("    public async Task PublishLocalEnvelopeAsync(DispatchEnvelope envelope, IServiceProvider scopedServices, CancellationToken cancellationToken)");
        sb.AppendLine("    {");
        sb.AppendLine("        IEvent @event = envelope.Type switch");
        sb.AppendLine("        {");

        foreach (var evt in events)
        {
            sb.AppendLine($"            \"{evt.FullTypeName}\" => JsonSerializer.Deserialize<{EmitConstants.ToCSharpTypeRef(evt.FullTypeName)}>(envelope.Payload, ConduitRuntime.JsonOptions)!,");
        }

        sb.AppendLine("            _ => throw new InvalidOperationException($\"Unknown event type: {envelope.Type}\")");
        sb.AppendLine("        };");
        sb.AppendLine("        await PublishLocalAsync(scopedServices, @event, cancellationToken);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitContextStart(StringBuilder sb, string messageTypeExpr, string messageKind,
        bool emitPayloadCapture = false, string? requestVarName = null, string? requestTypeName = null,
        bool isDoNotAudit = false)
    {
        // Build DispatchOptions from configure callback
        sb.AppendLine($"        {EmitConstants.DispatchOptions}? __dispatchOptions = null;");
        sb.AppendLine("        if (configure != null)");
        sb.AppendLine("        {");
        sb.AppendLine($"            __dispatchOptions = new {EmitConstants.DispatchOptions}();");
        sb.AppendLine("            configure(__dispatchOptions);");
        sb.AppendLine("        }");

        sb.AppendLine($"        var previousContext = {EmitConstants.MessageContext}.Current;");
        sb.AppendLine($"        {EmitConstants.MessageContext}.StartDispatch(__dispatchOptions);");
        // Attach this host's observer (DI singleton -> per-host) to the per-flow context, so audit
        // observation is isolated per host rather than routed through a process-global static.
        sb.AppendLine($"        {EmitConstants.MessageContext}.Current?.AttachObserver(serviceProvider.GetService<Conduit.Runtime.IConduitObserver>());");

        // Payload capture for non-DoNotAudit types -- only when an observer is attached, so a host without AddAudit
        // never serializes (MessageContext.HasObserver), and only for a type whose body is kept (CapturesAuditPayload:
        // not suppressed by the host's audit registration), so a suppressed type cannot fail its dispatch through capture.
        if (emitPayloadCapture && !isDoNotAudit && requestVarName != null)
        {
            var typeExpr = requestTypeName != null
                ? $"typeof({requestTypeName})"   // Strongly typed: use typeof(T) for efficient serialization
                : $"{requestVarName}.GetType()"; // Dynamic type (events via PublishAsync)
            sb.AppendLine($"        if ({EmitConstants.MessageContext}.Current is {{ HasObserver: true }} __auditContext && ConduitRuntime.CapturesAuditPayload({typeExpr}))");
            sb.AppendLine("        {");
            sb.AppendLine($"            __auditContext.SetPayload(JsonSerializer.SerializeToElement({requestVarName}, {typeExpr}, ConduitRuntime.AuditJsonOptions));");
            sb.AppendLine("        }");
        }

        sb.AppendLine($"        {EmitConstants.MessageContext_Observe}(new {EmitConstants.DispatchInvoked}({messageTypeExpr}, \"{messageKind}\"));");
        sb.AppendLine("        var __sw = Stopwatch.GetTimestamp();");

        sb.AppendLine($"        using var __activity = {EmitConstants.ConduitTelemetry}.StartActivity(\"ConduitMediator\", {messageTypeExpr}, \"{messageKind}\", \"DispatchAsync\");");
        sb.AppendLine("        try");
        sb.AppendLine("        {");
    }

    private static void EmitContextEnd(StringBuilder sb)
    {
        sb.AppendLine("        }");
        sb.AppendLine("        catch (Exception __ex)");
        sb.AppendLine("        {");
        sb.AppendLine("            var __failElapsed = Stopwatch.GetElapsedTime(__sw).TotalMilliseconds;");
        sb.AppendLine($"            {EmitConstants.MessageContext_Observe}(new {EmitConstants.DispatchFailed}(__failElapsed, __ex.Message, __ex.GetType().FullName ?? __ex.GetType().Name));");
        sb.AppendLine("            throw;");
        sb.AppendLine("        }");
        sb.AppendLine("        finally");
        sb.AppendLine("        {");
        sb.AppendLine($"            {EmitConstants.MessageContext}.RestoreContext(previousContext);");
        sb.AppendLine("        }");
    }

    /// <summary>
    /// Emits DispatchCompleted observation with elapsed time tracking.
    /// Uses a nested block to avoid variable name conflicts across return paths.
    /// </summary>
    private static void EmitDispatchCompleted(StringBuilder sb, string indent)
    {
        sb.AppendLine($"{indent}{{ var __elapsed = Stopwatch.GetElapsedTime(__sw).TotalMilliseconds;");
        sb.AppendLine($"{indent}{EmitConstants.MessageContext_Observe}(new {EmitConstants.DispatchCompleted}(__elapsed)); }}");
    }

    /// <summary>
    /// The expression a wire-dispatch arm reads its message with: <c>DeserializeWire</c>, wrapped in
    /// <c>CaptureAuditPayload</c> so the typed object becomes the dispatch's redacted audit payload -- unless the type is
    /// <c>[DoNotAudit]</c> at type level, which captures nothing (the same compile-time decision
    /// <see cref="EmitContextStart"/> makes for the in-process path).
    /// </summary>
    private static string WireRead(DispatchableTypeInfo type)
    {
        var read = $"ConduitRuntime.DeserializeWire<{EmitConstants.ToCSharpTypeRef(type.FullTypeName)}>(payload)";
        return type.IsDoNotAudit ? read : $"ConduitRuntime.CaptureAuditPayload({read})";
    }

