        sb.AppendLine("    IEnumerable<IInboundInterceptor> interceptors,");
        sb.AppendLine("    ConduitOptions conduitOptions,");
        sb.AppendLine("    ILogger<ConduitMediator> logger) : IWireMediator");
        sb.AppendLine("{");

