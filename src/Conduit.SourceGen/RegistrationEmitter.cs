using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Conduit.Analysis;

namespace Conduit.SourceGen;

/// <summary>
/// Emits the <c>AddConduit()</c> extension method that registers the mediator,
/// handlers, listeners, and <c>ConduitTypeRegistry</c> in DI.
/// </summary>
public static class RegistrationEmitter
{
    /// <summary>
    /// Generates the DI registration source code.
    /// </summary>
    /// <param name="handlers">All discovered handler registrations.</param>
    /// <param name="listenerGroups">All discovered event listener groups.</param>
    /// <param name="types">All discovered dispatchable types (used for type registry population).</param>
    public static string Emit(
        IReadOnlyList<HandlerInfo> handlers,
        IReadOnlyList<ListenerGroup> listenerGroups,
        IReadOnlyList<DispatchableTypeInfo> types)
    {
        if (handlers is null)
        {
            throw new ArgumentNullException(nameof(handlers));
        }

        if (listenerGroups is null)
        {
            throw new ArgumentNullException(nameof(listenerGroups));
        }

        if (types is null)
        {
            throw new ArgumentNullException(nameof(types));
        }

        var typesByName = types.ToDictionary(t => t.FullTypeName);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine();
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine();
        sb.AppendLine($"namespace {EmitConstants.NamespaceGenerated};");
        sb.AppendLine();
        sb.AppendLine("[System.CodeDom.Compiler.GeneratedCode(\"Conduit.SourceGen\", \"1.0.0\")]");
        sb.AppendLine("internal static class ConduitRegistration");
        sb.AppendLine("{");
        sb.AppendLine($"    public static IServiceCollection AddConduit(");
        sb.AppendLine($"        this IServiceCollection services,");
        sb.AppendLine($"        System.Action<{EmitConstants.ConduitBuilder}>? configure = null)");
        sb.AppendLine("    {");
        sb.AppendLine("        // Register core infrastructure (options, routing)");
        sb.AppendLine($"        {EmitConstants.ConduitRuntime}.AddConduitCore(services, configure);");
        sb.AppendLine();

        foreach (var handler in handlers)
        {
            if (!typesByName.TryGetValue(handler.MessageFullTypeName, out var type))
            {
                continue;
            }

            var typeRef = EmitConstants.ToCSharpTypeRef(type.FullTypeName);
            var interfaceType = type.Kind switch
            {
                DispatchableKind.Command =>
                    $"{EmitConstants.NamespaceHandlers}.ICommandHandler<{typeRef}, {type.ResultFullTypeName}>",
                DispatchableKind.VoidCommand =>
                    $"{EmitConstants.NamespaceHandlers}.ICommandHandler<{typeRef}>",
                DispatchableKind.Query =>
                    $"{EmitConstants.NamespaceHandlers}.IQueryHandler<{typeRef}, {type.ResultFullTypeName}>",
                DispatchableKind.Event or DispatchableKind.Model or _ => null,
            };

            if (interfaceType != null)
            {
                sb.AppendLine($"        services.AddTransient<{interfaceType}, {handler.HandlerFullTypeName}>();");
            }
        }

        foreach (var group in listenerGroups)
        {
            var eventTypeRef = EmitConstants.ToCSharpTypeRef(group.EventFullTypeName);
            foreach (var listener in group.ListenerFullTypeNames)
            {
                sb.AppendLine($"        services.AddTransient<{EmitConstants.NamespaceHandlers}.IEventListener<{eventTypeRef}>, {listener}>();");
            }
        }

        sb.AppendLine();
        sb.AppendLine("        services.AddTransient<ConduitMediator>();");
        sb.AppendLine($"        services.AddTransient<{EmitConstants.IMediator}>(sp => sp.GetRequiredService<ConduitMediator>());");
        sb.AppendLine($"        services.AddTransient<{EmitConstants.IWireMediator}>(sp => sp.GetRequiredService<ConduitMediator>());");
        sb.AppendLine($"        services.AddTransient<{EmitConstants.ILocalEnvelopeDispatcher}>(sp => sp.GetRequiredService<ConduitMediator>());");

        // Collect type lists for the registry
        var eventTypeNames = listenerGroups.Select(g => g.EventFullTypeName).Distinct().ToList();
        var commandTypeNames = handlers
            .Where(h => typesByName.TryGetValue(h.MessageFullTypeName, out var t)
                && (t.Kind == DispatchableKind.Command || t.Kind == DispatchableKind.VoidCommand))
            .Select(h => h.MessageFullTypeName)
            .Distinct()
            .ToList();
        var queryTypeNames = handlers
            .Where(h => typesByName.TryGetValue(h.MessageFullTypeName, out var t)
                && t.Kind == DispatchableKind.Query)
            .Select(h => h.MessageFullTypeName)
            .Distinct()
            .ToList();

        // Emit ConduitTypeRegistry registration
        sb.AppendLine();
        sb.AppendLine($"        // Compile-time type registry for transport topology discovery");
        sb.Append($"        services.AddSingleton(new {EmitConstants.ConduitTypeRegistry}(");
        sb.AppendLine();

        // Event types
        sb.Append("            eventTypes: [");
        for (var i = 0; i < eventTypeNames.Count; i++)
        {
            if (i > 0)
            {
                sb.Append(", ");
            }

            sb.Append($"typeof({EmitConstants.ToCSharpTypeRef(eventTypeNames[i])})");
        }

        sb.AppendLine("],");

        // Command types
        sb.Append("            commandTypes: [");
        for (var i = 0; i < commandTypeNames.Count; i++)
        {
            if (i > 0)
            {
                sb.Append(", ");
            }

            sb.Append($"typeof({EmitConstants.ToCSharpTypeRef(commandTypeNames[i])})");
        }

        sb.AppendLine("],");

        // Query types
        sb.Append("            queryTypes: [");
        for (var i = 0; i < queryTypeNames.Count; i++)
        {
            if (i > 0)
            {
                sb.Append(", ");
            }

            sb.Append($"typeof({EmitConstants.ToCSharpTypeRef(queryTypeNames[i])})");
        }

        sb.AppendLine("]));");

        sb.AppendLine();
        sb.AppendLine("        return services;");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }
}
