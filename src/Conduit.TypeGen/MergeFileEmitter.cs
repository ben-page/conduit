using System.Globalization;
using System.Reflection;
using System.Text;
using Conduit.Analysis;

namespace Conduit.TypeGen;

/// <summary>
/// Emits the top-level TypeScript file that inlines interfaces, type maps,
/// and the typed <c>ConduitClient</c> class with <c>execute</c>, <c>fetch</c>,
/// <c>publish</c>, and <c>on</c> methods. Re-exports transports and error types
/// from <c>./conduit</c>.
/// </summary>
public static class MergeFileEmitter
{
    /// <summary>
    /// Generates the merge file content for the given types.
    /// </summary>
    /// <param name="types">The dispatchable types.</param>
    /// <param name="assemblies">The assemblies to resolve types from (may be from MetadataLoadContext).</param>
    /// <param name="includeSignalR">Whether to re-export the SignalR transport.</param>
    /// <returns>The generated TypeScript source.</returns>
    public static string Emit(IReadOnlyList<DispatchableTypeInfo> types, IReadOnlyList<Assembly>? assemblies = null, bool includeSignalR = true)
    {
        ArgumentNullException.ThrowIfNull(types);

        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by Conduit.TypeGen - do not edit");
        sb.AppendLine();
        sb.AppendLine("import type { ConduitTransport, DispatchResult, Subscription } from './conduit';");
        sb.AppendLine();

        // Every TypeScript interface identifier emitted so far, keyed by that identifier, valued by the full
        // type name it came from. EmitErrorTypes checks a would-be error-type name against this so an error
        // type can never silently collide with an already-emitted DTO/command/query/event interface.
        var emittedTypeNames = new Dictionary<string, string>(StringComparer.Ordinal);

        // Emit type interfaces for [ClientVisible] types
        foreach (var typeInfo in types)
        {
            var resolvedType = assemblies != null
                ? TypeCollector.ResolveType(assemblies, typeInfo.FullTypeName)
                : null;
            var tsName = EmitInterface(sb, typeInfo.TypeName, resolvedType, typeInfo.BaseTypeName);
            emittedTypeNames[tsName] = typeInfo.FullTypeName;
            sb.AppendLine();
        }

        // Discover and emit transitively-referenced types (Domain DTOs, etc.)
        // Seeds from both [ClientVisible] type properties AND query/command result types
        if (assemblies != null)
        {
            var rootNames = types.Select(t => t.FullTypeName).ToList();
            var resultTypes = types
                .Where(t => t.ResultFullTypeName is not null)
                .Select(t => ResolveResultRootType(t.ResultFullTypeName!, assemblies))
                .OfType<Type>()
                .ToList();

            var referencedTypes = TypeCollector.CollectReferencedTypes(rootNames, resultTypes, assemblies);
            foreach (var collected in referencedTypes)
            {
                var tsName = EmitInterface(sb, collected.Type.Name, collected.Type, collected.BaseTypeName);
                emittedTypeNames[tsName] = collected.Type.FullName ?? collected.Type.Name;
                sb.AppendLine();
            }
        }

        // Emit type maps
        TypeMapEmitter.EmitMaps(sb, types, assemblies);

        EmitErrorTypes(sb, assemblies is null ? [] : ErrorTypeScanner.Scan(assemblies), emittedTypeNames);

        // Emit type aliases
        var hasCommands = types.Any(t => t.Kind is DispatchableKind.Command or DispatchableKind.VoidCommand);
        var hasQueries = types.Any(t => t.Kind == DispatchableKind.Query);
        var hasEvents = types.Any(t => t.Kind == DispatchableKind.Event);

        sb.AppendLine(hasCommands ? "export type AllCommands = CommandMap;" : "export type AllCommands = {};");
        sb.AppendLine(hasQueries ? "export type AllQueries = QueryMap;" : "export type AllQueries = {};");
        sb.AppendLine(hasEvents ? "export type AllEvents = EventMap;" : "export type AllEvents = {};");
        sb.AppendLine();

        // Emit ConduitClient class
        EmitConduitClient(sb);

        // Re-exports
        sb.AppendLine("export { HttpTransport } from './conduit';");
        if (includeSignalR)
        {
            sb.AppendLine("export { SignalRTransport } from './conduit';");
        }

        sb.AppendLine("export type { ConduitTransport, DispatchResult, ConduitError, ConduitErrorDetail, Subscription } from './conduit';");

        return sb.ToString();
    }

    /// <summary>
    /// Resolves a result type name to its root complex type, recursively unwrapping
    /// collections and dictionaries (e.g. <c>List&lt;Dict&lt;string, MyDto&gt;&gt;</c> → <c>MyDto</c>).
    /// </summary>
    private static Type? ResolveResultRootType(string resultFullTypeName, IReadOnlyList<Assembly> assemblies)
    {
        var typeName = UnwrapToInnerType(resultFullTypeName);
        return TypeCollector.ResolveType(assemblies, typeName);
    }

    /// <summary>
    /// Recursively strips generic wrappers (List, IReadOnlyList, Dictionary value types, etc.)
    /// to find the innermost type name.
    /// </summary>
    private static string UnwrapToInnerType(string typeName)
    {
        while (true)
        {
            var angleBracket = typeName.IndexOf('<', StringComparison.Ordinal);
            if (angleBracket < 0)
            {
                return typeName;
            }

            var outerName = typeName[..angleBracket];
            var innerContent = typeName[(angleBracket + 1)..^1];

            if (TypeMapper.IsDictionaryFullName(outerName))
            {
                // For dictionaries, extract the value type (after the first comma at depth 0)
                var commaIndex = FindTopLevelComma(innerContent);
                if (commaIndex >= 0)
                {
                    typeName = innerContent[(commaIndex + 1)..].TrimStart();
                    continue;
                }
            }

            // For collections or unknown generics, take the inner content
            typeName = innerContent;
        }
    }

    /// <summary>
    /// Finds the index of the first comma at bracket depth 0.
    /// </summary>
    private static int FindTopLevelComma(string text)
    {
        var depth = 0;
        for (var i = 0; i < text.Length; i++)
        {
            switch (text[i])
            {
                case '<':
                    depth++;
                    break;
                case '>':
                    depth--;
                    break;
                case ',' when depth == 0:
                    return i;
                default:
                    break;
            }
        }

        return -1;
    }

    /// <returns>The TypeScript interface identifier this emitted (the generic-stripped name for a generic type).</returns>
    private static string EmitInterface(StringBuilder sb, string typeName, Type? type, string? baseTypeName = null)
    {
        var tsName = type is not null && type.IsGenericType ? GenericTsName(type) : typeName;

        var extendsClause = string.IsNullOrEmpty(baseTypeName)
            ? string.Empty
            : $" extends {baseTypeName}";

        sb.Append(CultureInfo.InvariantCulture, $"export interface {tsName}{extendsClause} {{").AppendLine();

        if (type != null)
        {
            var bindingFlags = string.IsNullOrEmpty(baseTypeName)
                ? BindingFlags.Public | BindingFlags.Instance
                : BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly;

            var properties = type.GetProperties(bindingFlags);
            foreach (var property in properties)
            {
                var tsType = TypeMapper.MapType(property.PropertyType);
                if (IsNullableReference(property) && !tsType.EndsWith(" | null", StringComparison.Ordinal))
                {
                    tsType = $"{tsType} | null";
                }

                var propName = TypeScriptEmitter.ToCamelCase(property.Name);
                sb.Append(CultureInfo.InvariantCulture, $"  {propName}: {tsType};").AppendLine();
            }
        }

        sb.AppendLine("}");
        return tsName;
    }

    /// <summary>TS name for a generic type definition: <c>PagedResult`1</c> → <c>PagedResult&lt;T&gt;</c>.</summary>
    private static string GenericTsName(Type type)
    {
        var name = type.Name;
        var tick = name.IndexOf('`', StringComparison.Ordinal);
        if (tick >= 0)
        {
            name = name[..tick];
        }

        // The collected type may be a closed instance (e.g. PagedResult<Item>); the open
        // generic definition's arguments are the type PARAMETERS (T, ...) we want for the
        // declaration header.
        var definition = type.IsGenericTypeDefinition ? type : type.GetGenericTypeDefinition();
        var parameters = definition.GetGenericArguments().Select(a => a.Name);
        return $"{name}<{string.Join(", ", parameters)}>";
    }

    /// <summary>
    /// Determines whether a reference-type property is annotated nullable (<c>string?</c>) by reading
    /// the C# compiler's <c>NullableAttribute</c> (per-member) / <c>NullableContextAttribute</c>
    /// (per-type default). Value types return false (their nullability is handled by the type map).
    /// Flag byte 2 = nullable, 1 = not-null, 0 = oblivious.
    /// </summary>
    private static bool IsNullableReference(PropertyInfo property)
    {
        if (property.PropertyType.IsValueType)
        {
            return false;
        }

        const string nullableAttr = "System.Runtime.CompilerServices.NullableAttribute";
        var memberNullable = property.GetCustomAttributesData()
            .FirstOrDefault(a => a.AttributeType.FullName == nullableAttr);
        if (memberNullable is not null && memberNullable.ConstructorArguments.Count == 1)
        {
            var arg = memberNullable.ConstructorArguments[0];
            if (arg.Value is byte flag)
            {
                return flag == 2;
            }

            if (arg.Value is IReadOnlyList<CustomAttributeTypedArgument> flags
                && flags.Count > 0 && flags[0].Value is byte first)
            {
                return first == 2;
            }
        }

        const string contextAttr = "System.Runtime.CompilerServices.NullableContextAttribute";
        for (var declaring = property.DeclaringType; declaring is not null; declaring = declaring.DeclaringType)
        {
            var ctx = declaring.GetCustomAttributesData()
                .FirstOrDefault(a => a.AttributeType.FullName == contextAttr);
            if (ctx is not null && ctx.ConstructorArguments.Count == 1
                && ctx.ConstructorArguments[0].Value is byte ctxFlag)
            {
                return ctxFlag == 2;
            }
        }

        return false;
    }

    /// <summary>
    /// Emits one TypeScript interface per <c>ConduitException</c> subclass that declares client data, then
    /// <c>ErrorMap</c> (keyed by full type name) and the <c>isError</c> narrowing helper.
    /// </summary>
    /// <remarks>
    /// Property names are camelCased with <see cref="TypeScriptEmitter.ToCamelCase"/> here, not
    /// <c>JsonNamingPolicy.CamelCase.ConvertName</c> (what <c>ConduitException.GetClientData</c> uses on the
    /// wire) — the two agree on every valid C# identifier (verified exhaustively; both only ever special-case
    /// runs of uppercase letters), so the generated interface's keys always match what the server sends.
    /// </remarks>
    /// <remarks>
    /// A data property of a complex type is mapped by <see cref="TypeMapper"/> to its type name, but that type
    /// only gets an emitted interface when something else makes it <c>[ClientVisible]</c> (this walk does not
    /// feed <see cref="TypeCollector"/>). An un-emitted type name here fails the CONSUMER'S compile — visible
    /// and cheap to fix — so keep refusal data to primitives, strings, and collections of them.
    /// </remarks>
    /// <param name="sb">The output being built.</param>
    /// <param name="errors">The error types to emit, from <see cref="ErrorTypeScanner.Scan"/>.</param>
    /// <param name="emittedTypeNames">
    /// Every TypeScript interface identifier this file has already emitted (DTOs, commands, queries, events),
    /// keyed by that identifier and valued by the full type name it came from — see
    /// <see cref="ThrowIfErrorTypeNameCollides"/>.
    /// </param>
    private static void EmitErrorTypes(
        StringBuilder sb, IReadOnlyList<ErrorTypeInfo> errors, IReadOnlyDictionary<string, string> emittedTypeNames)
    {
        ThrowIfErrorTypeNameCollides(errors, emittedTypeNames);

        foreach (var error in errors)
        {
            sb.Append(CultureInfo.InvariantCulture, $"export interface {error.TypeName} {{").AppendLine();
            foreach (var property in error.Properties)
            {
                var tsType = TypeMapper.MapType(property.PropertyType);
                if (IsNullableReference(property) && !tsType.EndsWith(" | null", StringComparison.Ordinal))
                {
                    tsType = $"{tsType} | null";
                }

                sb.Append(CultureInfo.InvariantCulture, $"  {TypeScriptEmitter.ToCamelCase(property.Name)}: {tsType};").AppendLine();
            }

            sb.AppendLine("}");
            sb.AppendLine();
        }

        if (errors.Count == 0)
        {
            sb.AppendLine("export interface ErrorMap {}");
        }
        else
        {
            sb.AppendLine("export interface ErrorMap {");
            foreach (var error in errors)
            {
                sb.Append(CultureInfo.InvariantCulture, $"  '{error.FullTypeName}': {error.TypeName};").AppendLine();
            }

            sb.AppendLine("}");
        }

        sb.AppendLine();
        sb.AppendLine("/** Narrows a dispatch error (or a client exception carrying `type`/`data`) to a declared refusal. */");
        sb.AppendLine("export function isError<K extends keyof ErrorMap>(error: unknown, type: K): error is { type: K; data: ErrorMap[K] } {");
        sb.AppendLine("  return typeof error === 'object' && error !== null && (error as { type?: unknown }).type === type;");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    /// <summary>
    /// Guards the identifiers <see cref="EmitErrorTypes"/> is about to emit. <see cref="ErrorTypeScanner.Scan"/>
    /// dedupes only by FULL type name, so two <c>ConduitException</c> subclasses in different namespaces that
    /// happen to share a short name would each get their own <c>ErrorMap</c> entry but collide on the same
    /// <c>export interface {ShortName}</c> identifier — TypeScript either silently merges the two declarations
    /// (masking a real type mismatch) or fails the consumer's compile, neither of which is a build-time signal
    /// here. The same collision is possible against a DTO/command/query/event interface this file already
    /// emitted (<paramref name="emittedTypeNames"/> — built from that emission, the cheap source of truth
    /// already at hand; there is no other one, since these names are computed as they're emitted, not tracked
    /// anywhere ahead of time). Throws <see cref="InvalidOperationException"/> naming both colliding full type
    /// names — TypeGen has no dedicated exception type; every hard generation error surfaces this way, since
    /// <see cref="TypeGenTask.Execute"/> catches any <see cref="Exception"/> and reports it via
    /// <c>Log.LogError</c>.
    /// </summary>
    /// <remarks>
    /// Internal, and unit-tested directly (<c>MergeFileEmitterShould</c>) rather than through
    /// <see cref="Emit"/>: constructing a real collision needs two same-short-named public types in the SAME
    /// scanned assembly, and <see cref="ErrorTypeScanner.Scan"/> always scans the whole assembly — adding such
    /// a pair permanently to the shared test project would trip this guard for every OTHER test that scans it
    /// (e.g. <c>EmitTheErrorMapAndDataInterfaces</c>), not just a test that wants to see it fire.
    /// </remarks>
    internal static void ThrowIfErrorTypeNameCollides(
        IReadOnlyList<ErrorTypeInfo> errors, IReadOnlyDictionary<string, string> emittedTypeNames)
    {
        var seenErrorTypeNames = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var error in errors)
        {
            if (seenErrorTypeNames.TryGetValue(error.TypeName, out var otherErrorFullName))
            {
                throw new InvalidOperationException(
                    $"Conduit TypeGen: '{otherErrorFullName}' and '{error.FullTypeName}' both declare client " +
                    $"data and would both emit 'export interface {error.TypeName}'. Rename one of them.");
            }

            seenErrorTypeNames[error.TypeName] = error.FullTypeName;

            if (emittedTypeNames.TryGetValue(error.TypeName, out var otherFullName))
            {
                throw new InvalidOperationException(
                    $"Conduit TypeGen: '{error.FullTypeName}' would emit 'export interface {error.TypeName}', " +
                    $"which this file already emits for '{otherFullName}'. Rename one of them.");
            }
        }
    }

    private static void EmitConduitClient(StringBuilder sb)
    {
        sb.AppendLine("export class ConduitClient {");
        sb.AppendLine("  constructor(private transport: ConduitTransport) {}");
        sb.AppendLine();
        sb.AppendLine("  execute<K extends keyof AllCommands>(");
        sb.AppendLine("    type: K,");
        sb.AppendLine("    request: AllCommands[K]['request']");
        sb.AppendLine("  ): Promise<DispatchResult<AllCommands[K]['response']>> {");
        sb.AppendLine("    return this.transport.sendRequest(type, request);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  fetch<K extends keyof AllQueries>(");
        sb.AppendLine("    type: K,");
        sb.AppendLine("    request: AllQueries[K]['request']");
        sb.AppendLine("  ): Promise<DispatchResult<AllQueries[K]['response']>> {");
        sb.AppendLine("    return this.transport.sendRequest(type, request);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  publish<K extends keyof AllEvents>(");
        sb.AppendLine("    type: K,");
        sb.AppendLine("    data: AllEvents[K]");
        sb.AppendLine("  ): Promise<void> {");
        sb.AppendLine("    return this.transport.sendEvent(type, data);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  on<K extends keyof AllEvents>(");
        sb.AppendLine("    event: K,");
        sb.AppendLine("    handler: (data: AllEvents[K]) => void");
        sb.AppendLine("  ): Subscription {");
        sb.AppendLine("    return this.transport.subscribe(event as string, handler as (data: unknown) => void);");
        sb.AppendLine("  }");
        sb.AppendLine("}");
        sb.AppendLine();
    }
}
