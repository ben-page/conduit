using System.Globalization;
using System.Reflection;
using System.Text;
using Conduit.Analysis;

namespace Conduit.TypeGen;

/// <summary>
/// Emits the top-level TypeScript file that inlines interfaces, type maps,
/// and the typed <c>ConduitClient</c> class with <c>execute</c>, <c>fetch</c>,
/// <c>publish</c>, and <c>on</c> methods. Re-exports transports and error types
/// from <c>./conduit</c>.
/// </summary>
public static class MergeFileEmitter
{
    /// <summary>
    /// Every fixed top-level identifier <see cref="Emit"/> declares, imports, or re-exports besides the
    /// dynamic DTO/command/query/event interfaces (tracked as they're emitted) and <c>CommandMap</c>/
    /// <c>QueryMap</c>/<c>EventMap</c> (returned by <see cref="TypeMapEmitter.EmitMaps"/> — derived, not
    /// hand-listed). These have no single emission point to derive from: they're string literals scattered
    /// across <see cref="Emit"/>, <see cref="EmitConduitClient"/>, and <see cref="EmitErrorTypes"/>. Kept as
    /// one list, right above <see cref="Emit"/> where it's consumed, so a literal added there is one glance
    /// away from this list. If a name below changes or a literal is added, update both.
    /// </summary>
    internal static readonly string[] FixedMergeFileNames =
    [
        // The static "import type { ... } from './conduit';" line.
        "ConduitTransport", "DispatchResult", "Subscription",
        // EmitConduitClient's class, and the AllCommands/AllQueries/AllEvents type aliases.
        "ConduitClient", "AllCommands", "AllQueries", "AllEvents",
        // The bottom re-export line: "export { HttpTransport }", conditionally "export { SignalRTransport }",
        // and "export type { ConduitTransport, DispatchResult, ConduitError, ConduitErrorDetail, Subscription }".
        "HttpTransport", "SignalRTransport", "ConduitError", "ConduitErrorDetail",
        // EmitErrorTypes's own fixed output: the ErrorMap interface and the isError function.
        "ErrorMap", "isError",
    ];

    /// <summary>
    /// Generates the merge file content for the given types.
    /// </summary>
    /// <param name="types">The dispatchable types.</param>
    /// <param name="assemblies">The assemblies to resolve types from (may be from MetadataLoadContext).</param>
    /// <param name="includeSignalR">Whether to re-export the SignalR transport.</param>
    /// <returns>The generated TypeScript source.</returns>
    public static string Emit(IReadOnlyList<DispatchableTypeInfo> types, IReadOnlyList<Assembly>? assemblies = null, bool includeSignalR = true)
    {
        ArgumentNullException.ThrowIfNull(types);

        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by Conduit.TypeGen - do not edit");
        sb.AppendLine();
        sb.AppendLine("import type { ConduitTransport, DispatchResult, Subscription } from './conduit';");
        sb.AppendLine();

        var emittedTypeNames = EmitInterfacesAndMaps(sb, types, assemblies);

        EmitErrorTypes(sb, assemblies is null ? [] : ErrorTypeScanner.Scan(assemblies), emittedTypeNames);

        // Emit type aliases
        var hasCommands = types.Any(t => t.Kind is DispatchableKind.Command or DispatchableKind.VoidCommand);
        var hasQueries = types.Any(t => t.Kind == DispatchableKind.Query);
        var hasEvents = types.Any(t => t.Kind == DispatchableKind.Event);

        sb.AppendLine(hasCommands ? "export type AllCommands = CommandMap;" : "export type AllCommands = {};");
        sb.AppendLine(hasQueries ? "export type AllQueries = QueryMap;" : "export type AllQueries = {};");
        sb.AppendLine(hasEvents ? "export type AllEvents = EventMap;" : "export type AllEvents = {};");
        sb.AppendLine();

        // Emit ConduitClient class
        EmitConduitClient(sb);

        // Re-exports
        sb.AppendLine("export { HttpTransport } from './conduit';");
        if (includeSignalR)
        {
            sb.AppendLine("export { SignalRTransport } from './conduit';");
        }

        sb.AppendLine("export type { ConduitTransport, DispatchResult, ConduitError, ConduitErrorDetail, Subscription } from './conduit';");

        return sb.ToString();
    }

    /// <summary>
    /// Emits every interface <see cref="Emit"/> declares before <see cref="EmitErrorTypes"/> runs -- the root
    /// <c>[ClientVisible]</c> types, <see cref="TypeCollector"/>-discovered referenced types, and the
    /// <c>CommandMap</c>/<c>QueryMap</c>/<c>EventMap</c> type maps -- and returns every identifier emitted
    /// that way, plus <see cref="FixedMergeFileNames"/>, as one reserved-name set.
    /// </summary>
    /// <returns>
    /// Every TypeScript identifier this file has already emitted or will always emit regardless of input,
    /// keyed by that identifier and valued by a description of where it came from — what
    /// <see cref="EmitErrorTypes"/> checks a would-be error-type name against via
    /// <see cref="ThrowIfErrorTypeNameCollides"/>, so an error type can never silently collide with one.
    /// </returns>
    /// <remarks>
    /// Pulled out of <see cref="Emit"/> (rather than left inline) so this reserved-name set — the actual
    /// wiring the collision guard depends on — is itself directly callable from a test with real inputs
    /// (<c>MergeFileEmitterShould.ThrowWhenAnErrorTypeNameCollidesWithAFixedMergeFileName</c>), not just
    /// reconstructed by hand there.
    /// </remarks>
    internal static Dictionary<string, string> EmitInterfacesAndMaps(
        StringBuilder sb, IReadOnlyList<DispatchableTypeInfo> types, IReadOnlyList<Assembly>? assemblies)
    {
        // Every TypeScript interface identifier emitted so far, keyed by that identifier, valued by the full
        // type name (or a description, for a fixed name) it came from.
        var emittedTypeNames = new Dictionary<string, string>(StringComparer.Ordinal);

        // Emit type interfaces for [ClientVisible] types
        foreach (var typeInfo in types)
        {
            var resolvedType = assemblies != null
                ? TypeCollector.ResolveType(assemblies, typeInfo.FullTypeName)
                : null;
            var tsName = EmitInterface(sb, typeInfo.TypeName, resolvedType, typeInfo.BaseTypeName);
            ReserveInterfaceName(emittedTypeNames, tsName, typeInfo.FullTypeName);
            sb.AppendLine();
        }

        // Discover and emit transitively-referenced types (Domain DTOs, etc.)
        // Seeds from both [ClientVisible] type properties AND query/command result types
        if (assemblies != null)
        {
            var rootNames = types.Select(t => t.FullTypeName).ToList();
            var resultTypes = types
                .Where(t => t.ResultFullTypeName is not null)
                .SelectMany(t => ResolveResultSeedTypes(t.ResultFullTypeName!, assemblies))
                .ToList();

            var referencedTypes = TypeCollector.CollectReferencedTypes(rootNames, resultTypes, assemblies);
            foreach (var collected in referencedTypes)
            {
                var tsName = EmitInterface(sb, collected.Type.Name, collected.Type, collected.BaseTypeName);
                ReserveInterfaceName(emittedTypeNames, tsName, collected.Type.FullName ?? collected.Type.Name);
                sb.AppendLine();
            }
        }

        // Emit type maps. EmitMaps' return -- the names it actually decided to emit, not a guess mirroring
        // its "Count > 0" conditionals -- is the source of truth for those three names too.
        var mapNames = TypeMapEmitter.EmitMaps(sb, types, assemblies);
        foreach (var mapName in mapNames)
        {
            ReserveFixedName(emittedTypeNames, mapName, $"the {mapName} type map TypeMapEmitter just emitted");
        }

        // Every other fixed name this file always declares/imports/re-exports, regardless of what types
        // were passed in -- see FixedMergeFileNames' doc comment for why this can't be derived the same way.
        foreach (var fixedName in FixedMergeFileNames)
        {
            ReserveFixedName(emittedTypeNames, fixedName, "a fixed identifier this file always imports, declares, or re-exports");
        }

        return emittedTypeNames;
    }

    /// <summary>
    /// Records the identifier an interface just emitted took (<c>PagedResult&lt;T&gt;</c> takes <c>PagedResult</c>), and
    /// refuses a second type taking it. Two DTOs that share a short name (<c>Orders.Item</c>, <c>Catalog.Item</c>) would
    /// be two <c>export interface Item</c> declarations, which TypeScript merges without a word -- the client would accept
    /// either shape for both -- so generation fails instead, naming both full type names, as it does for an error type
    /// (<see cref="ThrowIfErrorTypeNameCollides"/>).
    /// </summary>
    private static void ReserveInterfaceName(Dictionary<string, string> emittedTypeNames, string tsName, string fullTypeName)
    {
        var identifier = IdentifierOf(tsName);
        if (emittedTypeNames.TryGetValue(identifier, out var otherFullName) && otherFullName != fullTypeName)
        {
            throw new InvalidOperationException(
                $"Conduit TypeGen: '{otherFullName}' and '{fullTypeName}' would both emit 'export interface {identifier}', " +
                "which TypeScript would merge into one. Rename one of them.");
        }

        emittedTypeNames[identifier] = fullTypeName;
    }

    /// <summary>Records a fixed identifier the file declares or imports, and refuses it when an interface already took it.</summary>
    private static void ReserveFixedName(Dictionary<string, string> emittedTypeNames, string name, string description)
    {
        if (emittedTypeNames.TryGetValue(name, out var otherFullName))
        {
            throw new InvalidOperationException(
                $"Conduit TypeGen: '{otherFullName}' would emit 'export interface {name}', which is {description}. Rename it.");
        }

        emittedTypeNames[name] = description;
    }

    /// <summary>The identifier an interface declaration takes: its name without type parameters.</summary>
    private static string IdentifierOf(string tsName)
    {
        var angleBracket = tsName.IndexOf('<', StringComparison.Ordinal);
        return angleBracket < 0 ? tsName : tsName[..angleBracket];
    }

    /// <summary>
    /// The types a result's C#-style type name reaches, for <see cref="TypeCollector"/> to start its walk from -- the
    /// same reach as a property type's: an array's element (<c>Item[]</c> → <c>Item</c>); a nullable's or a collection's
    /// element and a dictionary's value; any other generic as its DEFINITION and its arguments
    /// (<c>Envelope&lt;Receipt&gt;</c> → <c>Envelope`1</c> and <c>Receipt</c>), so a wrapper used only as a result is
    /// declared rather than stripped to its argument. A name the scanned assemblies do not declare (a BCL type) reaches
    /// nothing.
    /// </summary>
    private static List<Type> ResolveResultSeedTypes(string typeName, IReadOnlyList<Assembly> assemblies)
    {
        typeName = typeName.Trim();

        if (typeName.EndsWith(']'))
        {
            return ResolveResultSeedTypes(typeName[..typeName.LastIndexOf('[')], assemblies);
        }

        var angleBracket = typeName.IndexOf('<', StringComparison.Ordinal);
        if (angleBracket < 0)
        {
            return TypeCollector.ResolveType(assemblies, typeName) is { } type ? [type] : [];
        }

        var arguments = TypeMapper.SplitTopLevel(typeName[(angleBracket + 1)..^1]);
        var definitionFullName = $"{typeName[..angleBracket]}`{arguments.Count}";

        if (TypeMapper.IsDictionaryFullName(definitionFullName))
        {
            return ResolveResultSeedTypes(arguments[1], assemblies);
        }

        var seeds = new List<Type>();
        if (definitionFullName != "System.Nullable`1"
            && !TypeMapper.IsCollectionFullName(definitionFullName)
            && TypeCollector.ResolveType(assemblies, definitionFullName) is { } definition)
        {
            seeds.Add(definition);
        }

        foreach (var argument in arguments)
        {
            seeds.AddRange(ResolveResultSeedTypes(argument, assemblies));
        }

        return seeds;
    }

    /// <summary>
    /// Emits one interface: its properties keyed and typed as <c>System.Text.Json</c> writes them with
    /// <c>ConduitRuntime.JsonOptions</c> -- a <c>[JsonPropertyName]</c> is the key (quoted when it is not an identifier),
    /// else the camelCased name; a <c>[JsonIgnore]</c> property is left out, and one ignored only conditionally
    /// (<c>WhenWritingNull</c>, ...) is optional. A <c>[JsonPolymorphic]</c> type's discriminator comes first, as
    /// <c>System.Text.Json</c> writes it (<see cref="DiscriminatorLine"/>).
    /// </summary>
    /// <returns>The TypeScript interface name this emitted (<c>PagedResult&lt;T&gt;</c> for a generic type).</returns>
    private static string EmitInterface(StringBuilder sb, string typeName, Type? type, string? baseTypeName = null)
    {
        var tsName = type is not null && type.IsGenericType ? GenericTsName(type) : typeName;

        var extendsClause = string.IsNullOrEmpty(baseTypeName)
            ? string.Empty
            : $" extends {baseTypeName}";

        sb.Append(CultureInfo.InvariantCulture, $"export interface {tsName}{extendsClause} {{").AppendLine();

        if (type != null)
        {
            if (DiscriminatorLine(type) is { } discriminator)
            {
                sb.Append(CultureInfo.InvariantCulture, $"  {discriminator}").AppendLine();
            }

            var bindingFlags = string.IsNullOrEmpty(baseTypeName)
                ? BindingFlags.Public | BindingFlags.Instance
                : BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly;

            var properties = type.GetProperties(bindingFlags);
            foreach (var property in properties)
            {
                var ignore = JsonMarks.IgnoreOf(property);
                if (ignore == JsonIgnoreKind.Always)
                {
                    continue;
                }

                var tsType = TypeMapper.MapType(property.PropertyType);
                if (IsNullableReference(property) && !tsType.EndsWith(" | null", StringComparison.Ordinal))
                {
                    tsType = $"{tsType} | null";
                }

                var propertyKey = JsonMarks.ToTsPropertyKey(JsonMarks.PropertyName(property) ?? TypeScriptEmitter.ToCamelCase(property.Name));
                var optional = ignore == JsonIgnoreKind.Conditional ? "?" : string.Empty;
                sb.Append(CultureInfo.InvariantCulture, $"  {propertyKey}{optional}: {tsType};").AppendLine();
            }
        }

        sb.AppendLine("}");
        return tsName;
    }

    /// <summary>
    /// The discriminator member <paramref name="type"/> carries on the wire, or <see langword="null"/>: on a polymorphic
    /// base, its key typed as the union of its derived types' discriminators (<c>kind: 'circle' | 'square';</c>), optional
    /// when an instance can arrive without it (the base is not abstract, or a derived type has no discriminator); on a type
    /// a polymorphic ancestor registers with a discriminator, the same key narrowed to its own (<c>kind: 'circle';</c>),
    /// which the base's union accepts, so <c>extends</c> holds. The key is often a C# property that must be
    /// <c>[JsonIgnore]</c>d (it would conflict with the metadata), so only the attributes say it is there.
    /// </summary>
    private static string? DiscriminatorLine(Type type)
    {
        if (JsonMarks.PolymorphismOf(type) is { Discriminators.Count: > 0 } own)
        {
            var literals = own.Discriminators.Select(d => d.Literal).Distinct(StringComparer.Ordinal);
            var optional = !type.IsAbstract || own.HasUndiscriminatedDerivedType ? "?" : string.Empty;
            return $"{JsonMarks.ToTsPropertyKey(own.PropertyName)}{optional}: {string.Join(" | ", literals)};";
        }

        for (var ancestor = type.BaseType; ancestor is not null; ancestor = ancestor.BaseType)
        {
            if (JsonMarks.PolymorphismOf(ancestor) is { } inherited
                && inherited.Discriminators.FirstOrDefault(d => d.DerivedFullName == type.FullName) is { Literal: { } literal })
            {
                return $"{JsonMarks.ToTsPropertyKey(inherited.PropertyName)}: {literal};";
            }
        }

        return null;
    }

    /// <summary>TS name for a generic type definition: <c>PagedResult`1</c> → <c>PagedResult&lt;T&gt;</c>.</summary>
    private static string GenericTsName(Type type)
    {
        var name = type.Name;
        var tick = name.IndexOf('`', StringComparison.Ordinal);
        if (tick >= 0)
        {
            name = name[..tick];
        }

        // TypeCollector collects a generic as its definition, but a root resolved by name may be anything; the
        // definition's arguments are the type PARAMETERS (T, ...) the declaration header wants.
        var definition = type.IsGenericTypeDefinition ? type : type.GetGenericTypeDefinition();
        var parameters = definition.GetGenericArguments().Select(a => a.Name);
        return $"{name}<{string.Join(", ", parameters)}>";
    }

    /// <summary>
    /// Determines whether a reference-type property is annotated nullable (<c>string?</c>) by reading
    /// the C# compiler's <c>NullableAttribute</c> (per-member) / <c>NullableContextAttribute</c>
    /// (per-type default). Value types return false (their nullability is handled by the type map).
    /// Flag byte 2 = nullable, 1 = not-null, 0 = oblivious.
    /// </summary>
    private static bool IsNullableReference(PropertyInfo property)
    {
        if (property.PropertyType.IsValueType)
        {
            return false;
        }

        const string nullableAttr = "System.Runtime.CompilerServices.NullableAttribute";
        var memberNullable = property.GetCustomAttributesData()
            .FirstOrDefault(a => a.AttributeType.FullName == nullableAttr);
        if (memberNullable is not null && memberNullable.ConstructorArguments.Count == 1)
        {
            var arg = memberNullable.ConstructorArguments[0];
            if (arg.Value is byte flag)
            {
                return flag == 2;
            }

            if (arg.Value is IReadOnlyList<CustomAttributeTypedArgument> flags
                && flags.Count > 0 && flags[0].Value is byte first)
            {
                return first == 2;
            }
        }

        return property.DeclaringType is { } declaringType
            && ResultNullabilityReader.NullableContextOf(declaringType) == 2;
    }

    /// <summary>
    /// Emits one TypeScript interface per client-typed subclass (an empty body when it declares none), then
    /// <c>ErrorMap</c> (keyed by full type name) and the <c>isError</c> narrowing helper.
    /// </summary>
    /// <remarks>
    /// Property names are camelCased with <see cref="TypeScriptEmitter.ToCamelCase"/> here, not
    /// <c>JsonNamingPolicy.CamelCase.ConvertName</c> (what <c>ConduitException.GetClientData</c> uses on the
    /// wire) — the two agree on every valid C# identifier (verified exhaustively; both only ever special-case
    /// runs of uppercase letters), so the generated interface's keys always match what the server sends.
    /// </remarks>
    /// <remarks>
    /// A data property of a complex type is mapped by <see cref="TypeMapper"/> to its type name, but that type
    /// only gets an emitted interface when something else makes it <c>[ClientVisible]</c> (this walk does not
    /// feed <see cref="TypeCollector"/>). An un-emitted type name here fails the CONSUMER'S compile — visible
    /// and cheap to fix — so keep refusal data to primitives, strings, and collections of them.
    /// </remarks>
    /// <param name="sb">The output being built.</param>
    /// <param name="errors">The error types to emit, from <see cref="ErrorTypeScanner.Scan"/>.</param>
    /// <param name="emittedTypeNames">
    /// Every TypeScript identifier this file has already emitted or will always emit regardless of input —
    /// the dynamic DTO/command/query/event interfaces, <c>CommandMap</c>/<c>QueryMap</c>/<c>EventMap</c>, and
    /// <see cref="FixedMergeFileNames"/> — keyed by that identifier and valued by a description of where it
    /// came from, for <see cref="ThrowIfErrorTypeNameCollides"/>.
    /// </param>
    private static void EmitErrorTypes(
        StringBuilder sb, IReadOnlyList<ErrorTypeInfo> errors, IReadOnlyDictionary<string, string> emittedTypeNames)
    {
        ThrowIfErrorTypeNameCollides(errors, emittedTypeNames);

        foreach (var error in errors)
        {
            sb.Append(CultureInfo.InvariantCulture, $"export interface {error.TypeName} {{").AppendLine();
            foreach (var property in error.Properties)
            {
                var tsType = TypeMapper.MapType(property.PropertyType);
                if (IsNullableReference(property) && !tsType.EndsWith(" | null", StringComparison.Ordinal))
                {
                    tsType = $"{tsType} | null";
                }

                sb.Append(CultureInfo.InvariantCulture, $"  {TypeScriptEmitter.ToCamelCase(property.Name)}: {tsType};").AppendLine();
            }

            sb.AppendLine("}");
            sb.AppendLine();
        }

        if (errors.Count == 0)
        {
            sb.AppendLine("export interface ErrorMap {}");
        }
        else
        {
            sb.AppendLine("export interface ErrorMap {");
            foreach (var error in errors)
            {
                sb.Append(CultureInfo.InvariantCulture, $"  '{error.FullTypeName}': {error.TypeName};").AppendLine();
            }

            sb.AppendLine("}");
        }

        sb.AppendLine();
        sb.AppendLine("/** Narrows a dispatch error (or a client exception carrying `type`/`data`) to a declared refusal. */");
        sb.AppendLine("export function isError<K extends keyof ErrorMap>(error: unknown, type: K): error is { type: K; data: ErrorMap[K] } {");
        sb.AppendLine("  return typeof error === 'object' && error !== null && (error as { type?: unknown }).type === type;");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    /// <summary>
    /// Guards the identifiers <see cref="EmitErrorTypes"/> is about to emit. <see cref="ErrorTypeScanner.Scan"/>
    /// dedupes only by FULL type name, so two <c>ConduitException</c> subclasses in different namespaces that
    /// happen to share a short name would each get their own <c>ErrorMap</c> entry but collide on the same
    /// <c>export interface {ShortName}</c> identifier — TypeScript either silently merges the two declarations
    /// (masking a real type mismatch) or fails the consumer's compile, neither of which is a build-time signal
    /// here. The same collision is possible against a DTO/command/query/event interface this file already
    /// emitted, against <c>CommandMap</c>/<c>QueryMap</c>/<c>EventMap</c>, or against any other fixed name this
    /// file always declares/imports/re-exports (<paramref name="emittedTypeNames"/> covers all three — see
    /// <see cref="Emit"/>, where it's built from each of those sources in turn, and
    /// <see cref="FixedMergeFileNames"/> for the third). Throws <see cref="InvalidOperationException"/> naming
    /// both colliding full type names (or a description, for a fixed name with no full type name of its own)
    /// — TypeGen has no dedicated exception type; every hard generation error surfaces this way, since
    /// <see cref="TypeGenTask.Execute"/> catches any <see cref="Exception"/> and reports it via
    /// <c>Log.LogError</c>.
    /// </summary>
    /// <remarks>
    /// Internal, and unit-tested directly (<c>MergeFileEmitterShould</c>) rather than through
    /// <see cref="Emit"/>: constructing a real collision needs two same-short-named public types in the SAME
    /// scanned assembly, and <see cref="ErrorTypeScanner.Scan"/> always scans the whole assembly — adding such
    /// a pair permanently to the shared test project would trip this guard for every OTHER test that scans it
    /// (e.g. <c>EmitTheErrorMapAndDataInterfaces</c>), not just a test that wants to see it fire.
    /// </remarks>
    internal static void ThrowIfErrorTypeNameCollides(
        IReadOnlyList<ErrorTypeInfo> errors, IReadOnlyDictionary<string, string> emittedTypeNames)
    {
        var seenErrorTypeNames = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var error in errors)
        {
            if (seenErrorTypeNames.TryGetValue(error.TypeName, out var otherErrorFullName))
            {
                throw new InvalidOperationException(
                    $"Conduit TypeGen: '{otherErrorFullName}' and '{error.FullTypeName}' are both client-typed " +
                    $"refusals and would both emit 'export interface {error.TypeName}'. Rename one of them.");
            }

            seenErrorTypeNames[error.TypeName] = error.FullTypeName;

            if (emittedTypeNames.TryGetValue(error.TypeName, out var otherFullName))
            {
                throw new InvalidOperationException(
                    $"Conduit TypeGen: '{error.FullTypeName}' would emit 'export interface {error.TypeName}', " +
                    $"which this file already emits for '{otherFullName}'. Rename one of them.");
            }
        }
    }

    private static void EmitConduitClient(StringBuilder sb)
    {
        sb.AppendLine("export class ConduitClient {");
        sb.AppendLine("  constructor(private transport: ConduitTransport) {}");
        sb.AppendLine();
        sb.AppendLine("  execute<K extends keyof AllCommands>(");
        sb.AppendLine("    type: K,");
        sb.AppendLine("    request: AllCommands[K]['request']");
        sb.AppendLine("  ): Promise<DispatchResult<AllCommands[K]['response']>> {");
        sb.AppendLine("    return this.transport.sendRequest(type, request);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  fetch<K extends keyof AllQueries>(");
        sb.AppendLine("    type: K,");
        sb.AppendLine("    request: AllQueries[K]['request']");
        sb.AppendLine("  ): Promise<DispatchResult<AllQueries[K]['response']>> {");
        sb.AppendLine("    return this.transport.sendRequest(type, request);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  publish<K extends keyof AllEvents>(");
        sb.AppendLine("    type: K,");
        sb.AppendLine("    data: AllEvents[K]");
        sb.AppendLine("  ): Promise<void> {");
        sb.AppendLine("    return this.transport.sendEvent(type, data);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  on<K extends keyof AllEvents>(");
        sb.AppendLine("    event: K,");
        sb.AppendLine("    handler: (data: AllEvents[K]) => void");
        sb.AppendLine("  ): Subscription {");
        sb.AppendLine("    return this.transport.subscribe(event as string, handler as (data: unknown) => void);");
        sb.AppendLine("  }");
        sb.AppendLine("}");
        sb.AppendLine();
    }
}
