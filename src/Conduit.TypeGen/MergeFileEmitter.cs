using System.Text;
using Conduit.Analysis;

namespace Conduit.TypeGen;

/// <summary>
/// Emits the top-level TypeScript file that re-exports types,
/// type aliases, and the typed <c>Mediator</c> client class.
/// </summary>
public static class MergeFileEmitter
{
    /// <summary>
    /// Generates the merge file content for the given types.
    /// </summary>
    /// <param name="types">The dispatchable types.</param>
    /// <returns>The generated TypeScript source.</returns>
    public static string Emit(IReadOnlyList<DispatchableTypeInfo> types)
    {
        ArgumentNullException.ThrowIfNull(types);

        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by Conduit.TypeGen - do not edit");
        sb.AppendLine();
        sb.AppendLine("import type { ConduitTransport, DispatchResult } from './conduit';");
        sb.AppendLine("export * from './default.generated';");
        sb.AppendLine();

        var hasCommands = types.Any(t => t.Kind == DispatchableKind.Command);
        var hasVoidCommands = types.Any(t => t.Kind == DispatchableKind.VoidCommand);
        var hasQueries = types.Any(t => t.Kind == DispatchableKind.Query);

        if (hasCommands)
        {
            sb.AppendLine("import type { CommandMap } from './default.generated';");
        }

        if (hasVoidCommands)
        {
            sb.AppendLine("import type { VoidCommandMap } from './default.generated';");
        }

        if (hasQueries)
        {
            sb.AppendLine("import type { QueryMap } from './default.generated';");
        }

        sb.AppendLine();

        // Type aliases for the mediator
        sb.AppendLine(hasCommands
            ? "export type AllCommands = CommandMap;"
            : "export type AllCommands = {};");
        sb.AppendLine(hasVoidCommands
            ? "export type AllVoidCommands = VoidCommandMap;"
            : "export type AllVoidCommands = {};");
        sb.AppendLine(hasQueries
            ? "export type AllQueries = QueryMap;"
            : "export type AllQueries = {};");
        sb.AppendLine();

        // Typed mediator class
        sb.AppendLine("export class Mediator {");
        sb.AppendLine("  constructor(private transport: ConduitTransport) {}");
        sb.AppendLine();
        sb.AppendLine("  execute<K extends keyof AllCommands>(");
        sb.AppendLine("    type: K,");
        sb.AppendLine("    request: AllCommands[K]['request']");
        sb.AppendLine("  ): Promise<DispatchResult<AllCommands[K]['response']>> {");
        sb.AppendLine("    return this.transport.dispatch(type, request);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  executeVoid<K extends keyof AllVoidCommands>(");
        sb.AppendLine("    type: K,");
        sb.AppendLine("    request: AllVoidCommands[K]['request']");
        sb.AppendLine("  ): Promise<DispatchResult<void>> {");
        sb.AppendLine("    return this.transport.dispatch(type, request);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  fetch<K extends keyof AllQueries>(");
        sb.AppendLine("    type: K,");
        sb.AppendLine("    request: AllQueries[K]['request']");
        sb.AppendLine("  ): Promise<DispatchResult<AllQueries[K]['response']>> {");
        sb.AppendLine("    return this.transport.dispatch(type, request);");
        sb.AppendLine("  }");
        sb.AppendLine("}");

        return sb.ToString();
    }
}
