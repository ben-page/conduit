using System.Globalization;
using System.Text;
using Conduit.Analysis;

namespace Conduit.TypeGen;

/// <summary>
/// Emits the top-level TypeScript merge file that re-exports all namespace files
/// and composes the unified type maps and typed <c>Mediator</c> client class.
/// </summary>
public static class MergeFileEmitter
{
    /// <summary>
    /// Generates the merge file content for the given namespace groups.
    /// </summary>
    /// <param name="groups">The namespace groups to merge.</param>
    /// <returns>The generated TypeScript source.</returns>
    public static string Emit(IReadOnlyList<NamespaceGroup> groups)
    {
        ArgumentNullException.ThrowIfNull(groups);

        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by Conduit.TypeGen - do not edit");
        sb.AppendLine();
        sb.AppendLine("import type { ConduitTransport, DispatchResult } from './conduit';");

        // Import from each namespace file
        foreach (var group in groups)
        {
            var importFile = "./" + Path.GetFileNameWithoutExtension(group.FileName);
            var typeNames = group.Types.Select(t => t.TypeName).ToList();
            var mapNames = GetMapNames(group);

            var allImports = typeNames.Concat(mapNames).ToList();
            if (allImports.Count > 0)
            {
                sb.Append(CultureInfo.InvariantCulture, $"import type {{ {string.Join(", ", allImports)} }} from '{importFile}';").AppendLine();
            }
        }

        sb.AppendLine();

        // Re-export all types
        foreach (var group in groups)
        {
            var importFile = "./" + Path.GetFileNameWithoutExtension(group.FileName);
            sb.Append(CultureInfo.InvariantCulture, $"export * from '{importFile}';").AppendLine();
        }

        sb.AppendLine();

        // Composed type maps
        EmitComposedMaps(sb, groups);

        return sb.ToString();
    }

    private static List<string> GetMapNames(NamespaceGroup group)
    {
        var maps = new List<string>();
        if (group.Types.Any(t => t.Kind == DispatchableKind.Command))
        {
            maps.Add($"CommandMap as {GetPrefixedMapName(group, "CommandMap")}");
        }

        if (group.Types.Any(t => t.Kind == DispatchableKind.VoidCommand))
        {
            maps.Add($"VoidCommandMap as {GetPrefixedMapName(group, "VoidCommandMap")}");
        }

        if (group.Types.Any(t => t.Kind == DispatchableKind.Query))
        {
            maps.Add($"QueryMap as {GetPrefixedMapName(group, "QueryMap")}");
        }

        if (group.Types.Any(t => t.Kind == DispatchableKind.Event))
        {
            maps.Add($"EventMap as {GetPrefixedMapName(group, "EventMap")}");
        }

        return maps;
    }

    private static string GetPrefixedMapName(NamespaceGroup group, string mapName)
    {
        var prefix = group.Namespace.Replace(".", "", StringComparison.Ordinal);
        return $"{prefix}{mapName}";
    }

    private static void EmitComposedMaps(StringBuilder sb, IReadOnlyList<NamespaceGroup> groups)
    {
        EmitComposedMap(sb, groups, "AllCommands", DispatchableKind.Command, "CommandMap");
        EmitComposedMap(sb, groups, "AllVoidCommands", DispatchableKind.VoidCommand, "VoidCommandMap");
        EmitComposedMap(sb, groups, "AllQueries", DispatchableKind.Query, "QueryMap");
        EmitComposedMap(sb, groups, "AllEvents", DispatchableKind.Event, "EventMap");

        // Typed mediator class
        sb.AppendLine("export class Mediator {");
        sb.AppendLine("  constructor(private transport: ConduitTransport) {}");
        sb.AppendLine();
        sb.AppendLine("  execute<K extends keyof AllCommands>(");
        sb.AppendLine("    type: K,");
        sb.AppendLine("    request: AllCommands[K]['request']");
        sb.AppendLine("  ): Promise<DispatchResult<AllCommands[K]['response']>> {");
        sb.AppendLine("    return this.transport.dispatch(type, request);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  executeVoid<K extends keyof AllVoidCommands>(");
        sb.AppendLine("    type: K,");
        sb.AppendLine("    request: AllVoidCommands[K]['request']");
        sb.AppendLine("  ): Promise<DispatchResult<void>> {");
        sb.AppendLine("    return this.transport.dispatch(type, request);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  fetch<K extends keyof AllQueries>(");
        sb.AppendLine("    type: K,");
        sb.AppendLine("    request: AllQueries[K]['request']");
        sb.AppendLine("  ): Promise<DispatchResult<AllQueries[K]['response']>> {");
        sb.AppendLine("    return this.transport.dispatch(type, request);");
        sb.AppendLine("  }");
        sb.AppendLine("}");
    }

    private static void EmitComposedMap(
        StringBuilder sb,
        IReadOnlyList<NamespaceGroup> groups,
        string typeName,
        DispatchableKind kind,
        string mapName)
    {
        var relevantGroups = groups.Where(g => g.Types.Any(t => t.Kind == kind)).ToList();

        if (relevantGroups.Count == 0)
        {
            sb.Append(CultureInfo.InvariantCulture, $"export type {typeName} = {{}};").AppendLine();
        }
        else
        {
            var parts = relevantGroups.Select(g => GetPrefixedMapName(g, mapName));
            sb.Append(CultureInfo.InvariantCulture, $"export type {typeName} = {string.Join(" & ", parts)};").AppendLine();
        }

        sb.AppendLine();
    }
}
