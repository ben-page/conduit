namespace Conduit.TypeGen;

/// <summary>
/// Emits the base <c>conduit.ts</c> file containing shared TypeScript types
/// (<c>DispatchResult</c>, <c>ConduitTransport</c>, etc.) used by all generated code.
/// </summary>
public static class BaseFileEmitter
{
    /// <summary>
    /// Returns the base TypeScript file content.
    /// </summary>
    /// <returns>The generated TypeScript source.</returns>
    public static string Emit()
    {
        return @"// Auto-generated by Conduit.TypeGen - do not edit

export interface DispatchResult<T> {
  data?: T;
  error?: ConduitError;
}

export interface ConduitError {
  code: string;
  message: string;
  details?: ConduitErrorDetail[];
}

export interface ConduitErrorDetail {
  field?: string;
  message: string;
}

export interface ConduitTransport {
  dispatch<TResult>(type: string, payload: unknown): Promise<DispatchResult<TResult>>;
  subscribe(eventName: string, handler: (data: unknown) => void): Subscription;
}

export interface Subscription {
  unsubscribe(): void;
}
";
    }
}
