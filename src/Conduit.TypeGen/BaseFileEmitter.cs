using System.Text;

namespace Conduit.TypeGen;

/// <summary>
/// Emits the base <c>conduit.ts</c> file containing shared TypeScript types,
/// transport interface, and transport implementations.
/// </summary>
public static class BaseFileEmitter
{
    private static readonly HashSet<string> DefaultTransports =
        new(StringComparer.OrdinalIgnoreCase) { "Http", "SignalR" };

    /// <summary>
    /// Returns the base TypeScript file content with default transports (Http + SignalR).
    /// </summary>
    public static string Emit() => Emit(null);

    /// <summary>
    /// Returns the base TypeScript file content with the specified transports.
    /// </summary>
    /// <param name="transports">The transports to include. Defaults to Http + SignalR.</param>
    public static string Emit(HashSet<string>? transports)
    {
        transports ??= DefaultTransports;
        var includeSignalR = transports.Contains("SignalR");

        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by Conduit.TypeGen - do not edit");
        sb.AppendLine();

        if (includeSignalR)
        {
            sb.AppendLine("import { HubConnection } from '@microsoft/signalr';");
            sb.AppendLine();
        }

        EmitBaseTypes(sb);
        EmitTransportInterface(sb);
        EmitHttpTransport(sb);

        if (includeSignalR)
        {
            EmitSignalRTransport(sb);
        }

        return sb.ToString();
    }

    private static void EmitBaseTypes(StringBuilder sb)
    {
        sb.AppendLine("export interface DispatchResult<T> {");
        sb.AppendLine("  data?: T;");
        sb.AppendLine("  error?: ConduitError;");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export interface ConduitError {");
        sb.AppendLine("  code: string;");
        sb.AppendLine("  message: string;");
        sb.AppendLine("  details?: ConduitErrorDetail[];");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export interface ConduitErrorDetail {");
        sb.AppendLine("  field?: string;");
        sb.AppendLine("  message: string;");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void EmitTransportInterface(StringBuilder sb)
    {
        sb.AppendLine("export interface ConduitTransport {");
        sb.AppendLine("  sendRequest<TResult>(type: string, payload: unknown): Promise<DispatchResult<TResult>>;");
        sb.AppendLine("  sendEvent(type: string, data: unknown): Promise<void>;");
        sb.AppendLine("  subscribe(eventName: string, handler: (data: unknown) => void): Subscription;");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export interface Subscription {");
        sb.AppendLine("  unsubscribe(): void;");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void EmitHttpTransport(StringBuilder sb)
    {
        sb.AppendLine("export class HttpTransport implements ConduitTransport {");
        sb.AppendLine("  constructor(private baseUrl: string, private path: string = '/api/dispatch') {}");
        sb.AppendLine();
        sb.AppendLine("  async sendRequest<TResult>(type: string, payload: unknown): Promise<DispatchResult<TResult>> {");
        sb.AppendLine("    const response = await fetch(this.baseUrl + this.path, {");
        sb.AppendLine("      method: 'POST',");
        sb.AppendLine("      headers: { 'Content-Type': 'application/json' },");
        sb.AppendLine("      body: JSON.stringify({ type, payload }),");
        sb.AppendLine("    });");
        sb.AppendLine("    if (!response.ok) {");
        sb.AppendLine("      const text = await response.text();");
        sb.AppendLine("      try { return JSON.parse(text) as DispatchResult<TResult>; }");
        sb.AppendLine("      catch { throw new Error(`Conduit dispatch failed with status ${response.status}: ${text}`); }");
        sb.AppendLine("    }");
        sb.AppendLine("    return await response.json() as DispatchResult<TResult>;");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  async sendEvent(type: string, data: unknown): Promise<void> {");
        sb.AppendLine("    const response = await fetch(this.baseUrl + this.path + '/publish', {");
        sb.AppendLine("      method: 'POST',");
        sb.AppendLine("      headers: { 'Content-Type': 'application/json' },");
        sb.AppendLine("      body: JSON.stringify({ type, payload: data }),");
        sb.AppendLine("    });");
        sb.AppendLine("    if (!response.ok) {");
        sb.AppendLine("      throw new Error(`Conduit publish failed with status ${response.status}`);");
        sb.AppendLine("    }");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  subscribe(_eventName: string, _handler: (data: unknown) => void): Subscription {");
        sb.AppendLine("    throw new Error('HttpTransport does not support event subscriptions. Use SignalRTransport for server-pushed events.');");
        sb.AppendLine("  }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void EmitSignalRTransport(StringBuilder sb)
    {
        sb.AppendLine("export class SignalRTransport implements ConduitTransport {");
        sb.AppendLine("  constructor(private connection: HubConnection) {}");
        sb.AppendLine();
        sb.AppendLine("  async sendRequest<TResult>(type: string, payload: unknown): Promise<DispatchResult<TResult>> {");
        sb.AppendLine("    return await this.connection.invoke<DispatchResult<TResult>>('Dispatch', type, payload);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  async sendEvent(type: string, data: unknown): Promise<void> {");
        sb.AppendLine("    await this.connection.invoke('Publish', type, data);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  subscribe(eventName: string, handler: (data: unknown) => void): Subscription {");
        sb.AppendLine("    this.connection.on(eventName, handler);");
        sb.AppendLine("    return { unsubscribe: () => this.connection.off(eventName, handler) };");
        sb.AppendLine("  }");
        sb.AppendLine("}");
        sb.AppendLine();
    }
}
