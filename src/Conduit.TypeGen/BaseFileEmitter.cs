using System.Text;

namespace Conduit.TypeGen;

/// <summary>
/// Emits the base <c>conduit.ts</c>: the shared TypeScript types, the transport interface and the
/// transports, assembled from the TypeScript files in <c>Transport/</c> (embedded resources) by
/// <see cref="TransportSource"/>.
/// </summary>
public static class BaseFileEmitter
{
    private const string DefaultBasePath = "/api/conduit";
    private const string DefaultHubPath = "/conduit";

    private static readonly HashSet<string> DefaultTransports =
        new(StringComparer.OrdinalIgnoreCase) { "Http", "SignalR" };

    /// <summary>
    /// Returns the base TypeScript file content with default transports (Http + SignalR).
    /// </summary>
    public static string Emit() => Emit(null, DefaultBasePath, DefaultHubPath);

    /// <summary>
    /// Returns the base TypeScript file content with the specified transports and paths.
    /// </summary>
    /// <param name="transports">The transports to include. Defaults to Http + SignalR.</param>
    /// <param name="basePath">The base path for Conduit HTTP endpoints.</param>
    /// <param name="hubPath">The path for the SignalR hub.</param>
    public static string Emit(HashSet<string>? transports, string basePath, string hubPath)
    {
        transports ??= DefaultTransports;

        // Each path goes into its own file BEFORE assembly, so a base path equal to the hub's default (or the reverse)
        // can never be replaced inside the other transport.
        var sources = new List<TransportSource>
        {
            TransportSource.Load("base.ts"),
            TransportSource.Load("http.ts").WithDefaultPath(DefaultBasePath, basePath),
        };

        if (transports.Contains("SignalR"))
        {
            sources.Add(TransportSource.Load("signalr.ts").WithDefaultPath(DefaultHubPath, hubPath));
        }

        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by Conduit.TypeGen - do not edit");
        sb.AppendLine();

        var packageImports = sources.SelectMany(source => source.PackageImports).ToList();
        if (packageImports.Count > 0)
        {
            foreach (var line in packageImports)
            {
                sb.AppendLine(line);
            }

            sb.AppendLine();
        }

        foreach (var source in sources)
        {
            foreach (var line in source.Body)
            {
                sb.AppendLine(line);
            }

            sb.AppendLine();
        }

        return sb.ToString();
    }
}
