using System.Text;

namespace Conduit.TypeGen;

/// <summary>
/// Emits the base <c>conduit.ts</c> file containing shared TypeScript types,
/// transport interface, and transport implementations.
/// </summary>
public static class BaseFileEmitter
{
    private const string DefaultBasePath = "/api/conduit";
    private const string DefaultHubPath = "/conduit";

    private static readonly HashSet<string> DefaultTransports =
        new(StringComparer.OrdinalIgnoreCase) { "Http", "SignalR" };

    /// <summary>
    /// Returns the base TypeScript file content with default transports (Http + SignalR).
    /// </summary>
    public static string Emit() => Emit(null, DefaultBasePath, DefaultHubPath);

    /// <summary>
    /// Returns the base TypeScript file content with the specified transports and paths.
    /// </summary>
    /// <param name="transports">The transports to include. Defaults to Http + SignalR.</param>
    /// <param name="basePath">The base path for Conduit HTTP endpoints.</param>
    /// <param name="hubPath">The path for the SignalR hub.</param>
    public static string Emit(HashSet<string>? transports, string basePath, string hubPath)
    {
        transports ??= DefaultTransports;
        var includeSignalR = transports.Contains("SignalR");

        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by Conduit.TypeGen - do not edit");
        sb.AppendLine();

        if (includeSignalR)
        {
            sb.AppendLine("import { HubConnectionBuilder, HubConnection, HubConnectionState } from '@microsoft/signalr';");
            sb.AppendLine("import type { IRetryPolicy, RetryContext } from '@microsoft/signalr';");
            sb.AppendLine();
        }

        EmitBaseTypes(sb);
        EmitTransportInterface(sb);
        EmitHttpTransport(sb, basePath);

        if (includeSignalR)
        {
            EmitSignalRTransport(sb, hubPath);
        }

        return sb.ToString();
    }

    private static void EmitBaseTypes(StringBuilder sb)
    {
        sb.AppendLine("export interface DispatchResult<T> {");
        sb.AppendLine("  data?: T;");
        sb.AppendLine("  error?: ConduitError;");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export interface ConduitError {");
        sb.AppendLine("  code: string;");
        sb.AppendLine("  message: string;");
        sb.AppendLine("  details?: ConduitErrorDetail[];");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export interface ConduitErrorDetail {");
        sb.AppendLine("  field?: string;");
        sb.AppendLine("  message: string;");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void EmitTransportInterface(StringBuilder sb)
    {
        sb.AppendLine("export interface ConduitTransport {");
        sb.AppendLine("  sendRequest<TResult>(type: string, payload: unknown, headers?: Record<string, string>): Promise<DispatchResult<TResult>>;");
        sb.AppendLine("  sendEvent(type: string, data: unknown, headers?: Record<string, string>): Promise<void>;");
        sb.AppendLine("  subscribe(eventName: string, handler: (data: unknown) => void): Subscription;");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export interface Subscription {");
        sb.AppendLine("  unsubscribe(): void;");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void EmitHttpTransport(StringBuilder sb, string basePath)
    {
        sb.AppendLine("export class HttpTransport implements ConduitTransport {");
        sb.AppendLine("  constructor(private baseUrl: string, private basePath: string = '" + basePath + "') {}");
        sb.AppendLine();
        sb.AppendLine("  async sendRequest<TResult>(type: string, payload: unknown, headers?: Record<string, string>): Promise<DispatchResult<TResult>> {");
        sb.AppendLine("    const response = await fetch(this.baseUrl + this.basePath + '/dispatch', {");
        sb.AppendLine("      method: 'POST',");
        sb.AppendLine("      headers: { 'Content-Type': 'application/json', 'X-Conduit-Type': type, ...(headers ?? {}) },");
        sb.AppendLine("      body: JSON.stringify(payload),");
        sb.AppendLine("    });");
        sb.AppendLine("    if (!response.ok) {");
        sb.AppendLine("      const text = await response.text();");
        sb.AppendLine("      try { return JSON.parse(text) as DispatchResult<TResult>; }");
        sb.AppendLine("      catch { throw new Error(`Conduit dispatch failed with status ${response.status}: ${text}`); }");
        sb.AppendLine("    }");
        sb.AppendLine("    return await response.json() as DispatchResult<TResult>;");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  async sendEvent(type: string, data: unknown, headers?: Record<string, string>): Promise<void> {");
        sb.AppendLine("    const response = await fetch(this.baseUrl + this.basePath + '/publish', {");
        sb.AppendLine("      method: 'POST',");
        sb.AppendLine("      headers: { 'Content-Type': 'application/json', 'X-Conduit-Type': type, ...(headers ?? {}) },");
        sb.AppendLine("      body: JSON.stringify(data),");
        sb.AppendLine("    });");
        sb.AppendLine("    if (!response.ok) {");
        sb.AppendLine("      throw new Error(`Conduit publish failed with status ${response.status}`);");
        sb.AppendLine("    }");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  subscribe(_eventName: string, _handler: (data: unknown) => void): Subscription {");
        sb.AppendLine("    throw new Error('HttpTransport does not support event subscriptions. Use SignalRTransport for server-pushed events.');");
        sb.AppendLine("  }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void EmitSignalRTransport(StringBuilder sb, string hubPath)
    {
        sb.AppendLine("/**");
        sb.AppendLine(" * The reconnect schedule a SignalRTransport uses unless its options supply another: 0 s, 2 s,");
        sb.AppendLine(" * 5 s, 10 s, then every 30 s for as long as the outage lasts.");
        sb.AppendLine(" *");
        sb.AppendLine(" * Unbounded on purpose. SignalR's stock withAutomaticReconnect() schedule is [0, 2 s, 10 s, 30 s],");
        sb.AppendLine(" * and then it stops for good. That suits a desktop tab and bricks an unattended screen: a wall-mounted");
        sb.AppendLine(" * kiosk that loses its network for a minute has nobody standing there to reload it.");
        sb.AppendLine(" */");
        sb.AppendLine("export const DEFAULT_RETRY_POLICY: IRetryPolicy = {");
        sb.AppendLine("  nextRetryDelayInMilliseconds(retryContext: RetryContext): number {");
        sb.AppendLine("    const schedule = [0, 2000, 5000, 10000, 30000];");
        sb.AppendLine("    return schedule[Math.min(retryContext.previousRetryCount, schedule.length - 1)] ?? 30000;");
        sb.AppendLine("  },");
        sb.AppendLine("};");
        sb.AppendLine();
        sb.AppendLine("/**");
        sb.AppendLine(" * The socket's lifecycle, as a consumer presents it.");
        sb.AppendLine(" *");
        sb.AppendLine(" * - stopped: nothing has started it yet, or the app called stop(). Never a loss.");
        sb.AppendLine(" * - connecting: a start is in flight.");
        sb.AppendLine(" * - connected: the socket is up.");
        sb.AppendLine(" * - reconnecting: the socket dropped and the retry policy is working on it.");
        sb.AppendLine(" * - disconnected: the socket closed and nothing is retrying. Only a transport built with");
        sb.AppendLine(" *   automaticReconnect: false, or one whose retry policy gave up, reaches it; otherwise a close");
        sb.AppendLine(" *   nobody asked for is followed by restarts on the policy's schedule, reported as reconnecting.");
        sb.AppendLine(" */");
        sb.AppendLine("export type TransportConnectionState = 'stopped' | 'connecting' | 'connected' | 'reconnecting' | 'disconnected';");
        sb.AppendLine();
        sb.AppendLine("export interface SignalRTransportOptions {");
        sb.AppendLine("  accessTokenFactory?: () => string | Promise<string>;");
        sb.AppendLine("  automaticReconnect?: boolean;");
        sb.AppendLine("  /** Replaces DEFAULT_RETRY_POLICY. Ignored when automaticReconnect is false. */");
        sb.AppendLine("  retryPolicy?: IRetryPolicy;");
        sb.AppendLine("  configure?: (builder: HubConnectionBuilder) => void;");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export class SignalRTransport implements ConduitTransport {");
        sb.AppendLine("  private connection: HubConnection;");
        sb.AppendLine("  private started?: Promise<void>;");
        sb.AppendLine("  private connectionState: TransportConnectionState = 'stopped';");
        sb.AppendLine("  private readonly connectionStateHandlers = new Set<(state: TransportConnectionState) => void>();");
        sb.AppendLine("  private readonly restartPolicy: IRetryPolicy;");
        sb.AppendLine("  private readonly restartsEnabled: boolean;");
        sb.AppendLine("  private restartTimer?: ReturnType<typeof setTimeout>;");
        sb.AppendLine("  private restartAttempt = 0;");
        sb.AppendLine("  private restartStartedAt = 0;");
        sb.AppendLine("  private connectedAt = 0;");
        sb.AppendLine("  private hasConnected = false;");
        sb.AppendLine();
        sb.AppendLine("  /** A connection up this long is healthy: the next close starts the backoff schedule over. */");
        sb.AppendLine("  private static readonly STABLE_CONNECTION_MS = 30000;");
        sb.AppendLine();
        sb.AppendLine("  constructor(pathOrConnection: string | HubConnection = '" + hubPath + "', options?: SignalRTransportOptions) {");
        sb.AppendLine("    if (typeof pathOrConnection === 'string') {");
        sb.AppendLine("      const builder = new HubConnectionBuilder()");
        sb.AppendLine("        .withUrl(pathOrConnection, { accessTokenFactory: options?.accessTokenFactory });");
        sb.AppendLine("      if (options?.automaticReconnect !== false) builder.withAutomaticReconnect(options?.retryPolicy ?? DEFAULT_RETRY_POLICY);");
        sb.AppendLine("      options?.configure?.(builder);");
        sb.AppendLine("      this.connection = builder.build();");
        sb.AppendLine("    } else {");
        sb.AppendLine("      this.connection = pathOrConnection;");
        sb.AppendLine("    }");
        sb.AppendLine("    this.restartPolicy = options?.retryPolicy ?? DEFAULT_RETRY_POLICY;");
        sb.AppendLine("    this.restartsEnabled = options?.automaticReconnect !== false;");
        sb.AppendLine("    this.connection.onreconnecting(() => this.setConnectionState('reconnecting'));");
        sb.AppendLine("    this.connection.onreconnected(() => this.reportConnected());");
        sb.AppendLine("    // stop() reports 'stopped' before it closes the socket, so the close it causes is not a loss.");
        sb.AppendLine("    this.connection.onclose(error => {");
        sb.AppendLine("      if (this.connectionState === 'stopped') return;");
        sb.AppendLine("      this.scheduleRestart(error);");
        sb.AppendLine("    });");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  /**");
        sb.AppendLine("   * Starts the hub on first use (or call eagerly after login to warm it), and starts it again after it died.");
        sb.AppendLine("   *");
        sb.AppendLine("   * A failed start is not cached, so the next dispatch retries. A resolved start is not trusted either:");
        sb.AppendLine("   * once the connection is Disconnected (the retry policy stopped, or the server closed it without");
        sb.AppendLine("   * allowing a reconnect) a memoized promise would stay resolved while every invoke() threw, so the");
        sb.AppendLine("   * live state decides. A dispatch during a restart wait connects at once: the pending timer is");
        sb.AppendLine("   * cancelled here, and a failure schedules the next attempt.");
        sb.AppendLine("   */");
        sb.AppendLine("  connect(): Promise<void> {");
        sb.AppendLine("    this.cancelRestart();");
        sb.AppendLine("    if (this.started && this.connection.state === HubConnectionState.Disconnected) {");
        sb.AppendLine("      this.started = undefined;");
        sb.AppendLine("    }");
        sb.AppendLine("    if (!this.started) {");
        sb.AppendLine("      if (this.connectionState !== 'reconnecting') this.setConnectionState('connecting');");
        sb.AppendLine("      this.started = this.connection.start()");
        sb.AppendLine("        .then(() => { this.reportConnected(); })");
        sb.AppendLine("        .catch(e => {");
        sb.AppendLine("          this.started = undefined;");
        sb.AppendLine("          if (this.connectionState !== 'stopped') this.scheduleRestart(e instanceof Error ? e : undefined);");
        sb.AppendLine("          throw e;");
        sb.AppendLine("        });");
        sb.AppendLine("    }");
        sb.AppendLine("    return this.started;");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  /** Stops the hub on purpose. Reports 'stopped' first, so the close this causes is never reported as a loss. */");
        sb.AppendLine("  async stop(): Promise<void> {");
        sb.AppendLine("    this.cancelRestart();");
        sb.AppendLine("    this.started = undefined;");
        sb.AppendLine("    this.restartAttempt = 0;");
        sb.AppendLine("    this.connectedAt = 0;");
        sb.AppendLine("    this.setConnectionState('stopped');");
        sb.AppendLine("    await this.connection.stop();");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  /**");
        sb.AppendLine("   * Subscribes to the socket's lifecycle. The handler is called at once with the current state, so a late");
        sb.AppendLine("   * subscriber never shows 'stopped' for a socket that is already up. Deliberately not on ConduitTransport:");
        sb.AppendLine("   * HttpTransport has no connection to report on.");
        sb.AppendLine("   */");
        sb.AppendLine("  onStateChange(handler: (state: TransportConnectionState) => void): Subscription {");
        sb.AppendLine("    this.connectionStateHandlers.add(handler);");
        sb.AppendLine("    handler(this.connectionState);");
        sb.AppendLine("    return { unsubscribe: () => { this.connectionStateHandlers.delete(handler); } };");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  async sendRequest<TResult>(type: string, payload: unknown, headers?: Record<string, string>): Promise<DispatchResult<TResult>> {");
        sb.AppendLine("    await this.connect();");
        sb.AppendLine("    return await this.connection.invoke<DispatchResult<TResult>>('Dispatch', type, payload, null, headers ?? null);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  async sendEvent(type: string, data: unknown, headers?: Record<string, string>): Promise<void> {");
        sb.AppendLine("    await this.connect();");
        sb.AppendLine("    await this.connection.invoke('Publish', type, data, null, headers ?? null);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  subscribe(eventName: string, handler: (data: unknown) => void): Subscription {");
        sb.AppendLine("    this.connection.on(eventName, handler);");
        sb.AppendLine("    void this.connect();");
        sb.AppendLine("    return { unsubscribe: () => this.connection.off(eventName, handler) };");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  private reportConnected(): void {");
        sb.AppendLine("    this.hasConnected = true;");
        sb.AppendLine("    this.connectedAt = Date.now();");
        sb.AppendLine("    this.setConnectionState('connected');");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  /**");
        sb.AppendLine("   * Keeps trying after a close the app did not ask for, and after a start that failed -- the paths");
        sb.AppendLine("   * withAutomaticReconnect does not cover. Waits come from the same retry policy the hub reconnects");
        sb.AppendLine("   * with, so one schedule and one option cover both. The attempt count resets only after a connection");
        sb.AppendLine("   * stayed up STABLE_CONNECTION_MS, so a server that accepts a connection and closes it at once is");
        sb.AppendLine("   * retried on the schedule rather than in a tight loop.");
        sb.AppendLine("   */");
        sb.AppendLine("  private scheduleRestart(error?: Error): void {");
        sb.AppendLine("    if (this.restartTimer !== undefined) return;");
        sb.AppendLine("    if (!this.restartsEnabled) { this.setConnectionState('disconnected'); return; }");
        sb.AppendLine("    if (this.connectedAt !== 0 && Date.now() - this.connectedAt >= SignalRTransport.STABLE_CONNECTION_MS) {");
        sb.AppendLine("      this.restartAttempt = 0;");
        sb.AppendLine("    }");
        sb.AppendLine("    this.connectedAt = 0;");
        sb.AppendLine("    if (this.restartAttempt === 0) this.restartStartedAt = Date.now();");
        sb.AppendLine("    const delay = this.restartPolicy.nextRetryDelayInMilliseconds({");
        sb.AppendLine("      previousRetryCount: this.restartAttempt,");
        sb.AppendLine("      elapsedMilliseconds: Date.now() - this.restartStartedAt,");
        sb.AppendLine("      retryReason: error ?? new Error('The connection closed without allowing a reconnect.'),");
        sb.AppendLine("    });");
        sb.AppendLine("    if (delay === null) { this.setConnectionState('disconnected'); return; }");
        sb.AppendLine("    this.restartAttempt += 1;");
        sb.AppendLine("    this.setConnectionState(this.hasConnected ? 'reconnecting' : 'connecting');");
        sb.AppendLine("    this.restartTimer = setTimeout(() => {");
        sb.AppendLine("      this.restartTimer = undefined;");
        sb.AppendLine("      void this.connect().catch(() => { /* the failure scheduled the next attempt */ });");
        sb.AppendLine("    }, delay);");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  private cancelRestart(): void {");
        sb.AppendLine("    if (this.restartTimer === undefined) return;");
        sb.AppendLine("    clearTimeout(this.restartTimer);");
        sb.AppendLine("    this.restartTimer = undefined;");
        sb.AppendLine("  }");
        sb.AppendLine();
        sb.AppendLine("  private setConnectionState(state: TransportConnectionState): void {");
        sb.AppendLine("    if (this.connectionState === state) return;");
        sb.AppendLine("    this.connectionState = state;");
        sb.AppendLine("    this.connectionStateHandlers.forEach(handler => handler(state));");
        sb.AppendLine("  }");
        sb.AppendLine("}");
        sb.AppendLine();
    }
}
