using System.Globalization;
using System.Reflection;
using System.Text;
using Conduit.Analysis;

namespace Conduit.TypeGen;

/// <summary>
/// Emits TypeScript interface definitions and type maps for dispatchable types.
/// </summary>
public static class TypeScriptEmitter
{
    /// <summary>
    /// Emits a complete TypeScript file with interfaces and type maps.
    /// </summary>
    /// <param name="types">The dispatchable types to emit.</param>
    /// <returns>The generated TypeScript source.</returns>
    public static string Emit(IReadOnlyList<DispatchableTypeInfo> types)
    {
        ArgumentNullException.ThrowIfNull(types);

        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by Conduit.TypeGen - do not edit");
        sb.AppendLine();

        foreach (var type in types)
        {
            EmitInterface(sb, type);
            sb.AppendLine();
        }

        TypeMapEmitter.EmitMaps(sb, types);

        return sb.ToString();
    }

    private static void EmitInterface(StringBuilder sb, DispatchableTypeInfo typeInfo)
    {
        sb.Append(CultureInfo.InvariantCulture, $"export interface {typeInfo.TypeName} {{").AppendLine();

        // Try to load the type to get its properties
        var type = FindType(typeInfo.FullTypeName);
        if (type != null)
        {
            var properties = type.GetProperties(BindingFlags.Public | BindingFlags.Instance);
            foreach (var property in properties)
            {
                var tsType = TypeMapper.MapType(property.PropertyType);
                var propName = ToCamelCase(property.Name);
                sb.Append(CultureInfo.InvariantCulture, $"  {propName}: {tsType};").AppendLine();
            }
        }

        sb.AppendLine("}");
    }

    internal static Type? FindType(string fullTypeName)
    {
        // Use Type.GetType which searches the calling assembly and mscorlib/System first,
        // then falls back to all loaded assemblies. This works correctly in the MSBuild
        // task context where the target assembly is loaded via MetadataLoadContext or
        // Assembly.LoadFrom.
        var type = Type.GetType(fullTypeName);
        if (type != null)
        {
            return type;
        }

        foreach (var assembly in AppDomain.CurrentDomain.GetAssemblies())
        {
            type = assembly.GetType(fullTypeName);
            if (type != null)
            {
                return type;
            }
        }

        return null;
    }

    /// <summary>
    /// Converts a PascalCase name to camelCase, handling acronyms correctly.
    /// <c>IPAddress</c> → <c>ipAddress</c>, <c>XMLParser</c> → <c>xmlParser</c>,
    /// <c>Name</c> → <c>name</c>, <c>ID</c> → <c>id</c>.
    /// </summary>
    internal static string ToCamelCase(string name)
    {
        if (string.IsNullOrEmpty(name))
        {
            return name;
        }

        // Find the length of the leading uppercase run
        var upperCount = 0;
        while (upperCount < name.Length && char.IsUpper(name[upperCount]))
        {
            upperCount++;
        }

        if (upperCount == 0)
        {
            return name;
        }

        // Single uppercase letter or all uppercase: lowercase the whole run
        // Multiple uppercase followed by lowercase: lowercase all but last (the last starts the next word)
        var lowercaseCount = upperCount == name.Length || upperCount == 1
            ? upperCount
            : upperCount - 1;

        return string.Concat(
            name[..lowercaseCount].ToLowerInvariant(),
            name[lowercaseCount..]);
    }
}
